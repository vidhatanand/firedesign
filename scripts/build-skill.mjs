#!/usr/bin/env node
// Builds the two lists the Fire skill (skills/fire) reads whole, so an agent can choose by meaning and not by keyword:
//   skills/fire/screens.md   every reference screen (templates/*.html): what it is for, when to use it, what to use
//                            instead, its states, its file and its picture. From contract/cards/templates/*.json.
//   skills/fire/parts.md     every component, pattern, layout, website section and module, one line each, by family.
//                            From contract/index.json.
// The rest of the skill (SKILL.md, contributing.md, where.mjs) is written by hand.
// Usage: node scripts/build-skill.mjs [--check]     --check exits 1 when a committed list is stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
const VERSION = read('package.json').version;
const HEAD = (what) => `<!-- GENERATED by scripts/build-skill.mjs from ${what}: edit the cards and rebuild, never this file. -->`;

/* ---------- screens.md ---------- */
// Where a person meets the screen: [title, about, test, place in the file]. The first group that matches wins.
const GROUPS = [
  ['Public website', 'Pages anyone can open, composed from website sections inside `fd-site`.', (c) => c.id.startsWith('site-'), 3],
  ['Documentation', 'Pages on the documentation shell.', (c) => c.id.startsWith('docs-'), 4],
  ['In the app', 'Screens behind sign-in, inside the app shell, and the screens around it (sign-in, not found, support).', (c) => c.surfaces.includes('app'), 1],
  ['Opened from a link, outside the app', 'Pages a person outside the account opens from an email, a chat or a shared link.', () => true, 2],
];
const sentence = (s) => s.trim().replace(/\.$/, '');

export function screens() {
  const dir = path.join(ROOT, 'contract/cards/templates');
  const cards = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => read(`contract/cards/templates/${f}`));
  const ids = new Set(cards.map((c) => c.id));
  const entry = (c) => {
    const lines = [`### ${c.id}`, '', c.job, ''];
    lines.push(`- **For:** ${c.surfaces.join(', ')} · shows or collects ${c.data.join(', ')}`);
    lines.push(`- **Use when:** ${c.useWhen.map(sentence).join('; ')}.`);
    if (c.avoidWhen.length) {
      lines.push(`- **Not when:** ${c.avoidWhen.map((a) => `${sentence(a.when)} → ${ids.has(a.instead) ? `\`${a.instead}\`` : a.instead.replace(/\.$/, '')}`).join('; ')}.`);
    }
    if (c.aka.length) lines.push(`- **Also called:** ${c.aka.join(', ')}`);
    lines.push(`- **States:** ${c.states.map((s) => s.name).join(', ')}`);
    if (c.sections) lines.push(`- **Sections, in order:** ${c.sections.map((s) => (s.variant ? `${s.section} (${s.variant})` : s.section)).join(', ')}`);
    lines.push(`- **Open:** \`${c.example}\` · picture \`contract/pictures/template/${c.id}.png\` · card \`contract/cards/templates/${c.id}.json\``);
    return lines.join('\n');
  };
  const index = [];
  const left = [...cards];
  const groups = GROUPS.map(([title, about, test, place]) => {
    const mine = left.filter(test);
    for (const c of mine) left.splice(left.indexOf(c), 1);
    if (mine.length) index.push([place, [`**${title}**`, ...mine.map((c) => `- \`${c.id}\` (${c.data.join(', ')}): ${c.job}`)].join('\n')]);
    return [place, mine.length ? [`## ${title}`, '', about, '', mine.map(entry).join('\n\n')].join('\n') : ''];
  }).filter(([, text]) => text).sort((a, b) => a[0] - b[0]).map(([, text]) => text);
  return `${HEAD('contract/cards/templates')}
# Fire's reference screens (${cards.length}, Fire ${VERSION})

Each is a whole screen built only from Fire's parts, with every state it needs. Choose by meaning: the person's task
and the shape of the data, not the words in the name. A list of invoices follows \`logs\`; a page for one customer
follows \`record\`.

1. Read the index below, all ${cards.length} lines. If your reader cut this file short, read it again in parts until you
   have seen every line of the index: a choice made from a search of this file is a guess.
2. Read the full entry of the two or three nearest (search this file for \`### <id>\`): "Use when" and "Not when" decide
   between them, and "Not when" names the screen to use instead.
3. Open the chosen screen's picture, then its file. Paths are relative to Fire's folder (\`node where.mjs\` beside this
   file prints it). A state opens at \`<file>?state=<name>\`; the screen's card says how to reach each one.

## Index

${index.sort((x, y) => x[0] - y[0]).map(([, text]) => text).join('\n\n')}

${groups.join('\n\n')}
`;
}

/* ---------- parts.md ---------- */
const KIND_NOTE = { pattern: 'pattern', layout: 'layout', section: 'website section', module: 'module' };

export function parts() {
  const idx = read('contract/index.json');
  const entries = idx.entries.filter((e) => e.kind !== 'template');
  const families = [...new Set(entries.map((e) => e.family))].sort((a, b) => a.localeCompare(b));
  const line = (e) => {
    const tags = [KIND_NOTE[e.kind], e.surfaces?.length ? e.surfaces.join(', ') : ''].filter(Boolean).join('; ');
    return `- \`${e.id}\`${tags ? ` (${tags})` : ''}: ${e.job}`;
  };
  const body = families.map((f) => [`## ${f}`, '', ...entries.filter((e) => e.family === f).sort((a, b) => a.id.localeCompare(b.id)).map(line)].join('\n')).join('\n\n');
  return `${HEAD('contract/index.json')}
# Fire's parts (${entries.length}, Fire ${VERSION})

One line for every component, pattern, layout, website section and module: its id, where it is used, and its job.
Search first (\`fire find "<what it does>"\`); read the family here when the search gives nothing close, because the
part may exist under a name you did not try. Then read the part's card in \`contract/catalog.json\` (when to use it and
what to use instead) and copy its markup from the docs section the card names. An id is not a class:
\`docs/_ref/CLASSES.md\` lists every class.

${body}
`;
}

/* ---------- run ---------- */
const OUTPUTS = { 'skills/fire/screens.md': screens, 'skills/fire/parts.md': parts };

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [rel, make] of Object.entries(OUTPUTS)) {
    const file = path.join(ROOT, rel);
    const text = make();
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) { console.error(`stale: ${rel} (run node scripts/build-skill.mjs)`); stale += 1; }
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
    }
  }
  if (stale) process.exit(1);
  console.log(`skill: ${Object.keys(OUTPUTS).length} lists ${check ? 'up to date' : 'written'}`);
}
