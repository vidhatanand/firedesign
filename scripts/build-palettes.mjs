#!/usr/bin/env node
// Writes fire/palettes.css from fire/js/palettes.js.
//   node scripts/build-palettes.mjs           write the file
//   node scripts/build-palettes.mjs --check   also print every palette's contrast ratios and fail on a violation,
//                                             assert ember equals the tokens.css literals and that a zero tone is
//                                             the identity, and sweep extreme tones through the contrast rules.
// The contrast rules (WCAG 2), in every palette, light and dark, default and high contrast:
//   --fd-text, --fd-text-2, --fd-text-3   4.5:1 on --fd-bg, --fd-bg-sunken, --fd-surface, --fd-surface-raised,
//                                         --fd-fill laid over each of them (a segmented track, a well's fill), and
//                                         --fd-accent-8 over the page and surface (the active nav item, a selected row)
//   --fd-text-4                           3:1 on the same (placeholders, disabled text, decorative icons only)
//   high contrast                         every text step mixes more ink than its default
//   --fd-accent-contrast                  4.5:1 on --fd-accent and on --fd-accent-hover, which moves away from the
//                                         label; here and in every [data-accent] block of tokens.css
//   --fd-<tone>-contrast on --fd-<tone>-fill   4.5:1 for success, warning, danger, info and violet, wherever
//                                         tokens.css declares them
//   --fd-accent-text                      4.5:1 on --fd-bg, --fd-surface and --fd-accent-8 over each, here and in
//                                         every [data-accent] block (against every palette's page and surface)
//   --fd-focus                            3:1 on the page, the well, the surfaces, the fill on each and the accent wash, in
//                                         every palette, toned map and [data-accent] block (against every palette),
//                                         and equal to focusOf(): the accent when it reaches 3:1, else the accent text
// The text steps are read from tokens.css and mixed exactly as the browser does: ink-wash at the step's alpha,
// composited in sRGB over the background.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const engine = await import(pathToFileURL(path.join(ROOT, 'fire/js/palettes.js')).href);
const { PALETTES, PALETTE_TOKENS, CONTRAST_TOKENS, TONE_DEFAULT, toneTokens, cssValue, contrast, toOklch, parse, washOver } = engine;
// The rules themselves live in fire/js/palette-rules.js, so fire/js/theme.js holds every palette it builds to them.
const rules = await import(pathToFileURL(path.join(ROOT, 'fire/js/palette-rules.js')).href);
const { TEXT_MIN, FAINT_MIN, TEXT_STEPS, TEXT_LADDER } = rules;

/* ---------- Write ---------- */
function build() {
  const out = [
    '/* ==========================================================================',
    '   Fire — palettes. GENERATED by scripts/build-palettes.mjs from fire/js/palettes.js; do not edit by hand.',
    '   --------------------------------------------------------------------------',
    '   <html data-palette="volt">, or data-palette on any subtree. Each palette sets the colour tokens below as',
    '   light-dark() pairs, so data-theme keeps working inside it; the ink ladder, text steps, fills, accent washes',
    '   and focus ring re-derive from them in tokens.css. With data-contrast="high" the lines step up in the',
    '   palette\'s own hue.',
    `   Palettes: ${PALETTES.map((p) => p.name).join(' · ')}`,
    '   ========================================================================== */',
    '',
  ];
  for (const p of PALETTES) {
    out.push(`/* ${p.label}: ${p.note} */`);
    out.push(`[data-palette="${p.name}"] {`);
    for (const key of PALETTE_TOKENS) out.push(`  ${key}: ${cssValue(p.tokens[key])};`);
    out.push('}');
    out.push(`[data-palette="${p.name}"][data-contrast="high"],`);
    out.push(`[data-contrast="high"] [data-palette="${p.name}"] {`);
    for (const key of CONTRAST_TOKENS) out.push(`  ${key}: ${cssValue(p.contrast[key])};`);
    out.push('}');
    out.push('');
  }
  const file = path.join(ROOT, 'fire/palettes.css');
  fs.writeFileSync(file, out.join('\n'));
  console.log(`wrote ${path.relative(ROOT, file)} (${PALETTES.length} palettes)`);
}

/* ---------- Check ---------- */
const errors = [];
const fail = (msg) => errors.push(msg);
const r2 = (n) => n.toFixed(2).padStart(5);
const L = (c) => toOklch(parse(c).rgb)[0];

/* ---------- tokens.css, read as the browser reads it ---------- */
const CSS = fs.readFileSync(path.join(ROOT, 'fire/tokens.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
// Every innermost rule as [selector, body]; a media block's own prelude is dropped by the regex.
const RULES = [...CSS.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map((m) => [m[1].trim().replace(/\s+/g, ' '), m[2]]);
const decls = (text) => Object.fromEntries([...text.matchAll(/(--fd-[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim().replace(/\s+/g, ' ')]));
function block(selector) {
  const found = RULES.filter(([s]) => s === selector);
  if (!found.length) throw new Error(`tokens.css: block ${selector} not found`);
  return found.map(([, body]) => body).join('\n');
}
const LADDER = decls(block(':root, [data-palette]'));
const HIGH_SELECTOR = '[data-contrast="high"], [data-contrast="high"] [data-palette]';
const HIGH = decls(block(HIGH_SELECTOR));

/** Split a CSS value on its top-level commas. */
function args(text) {
  const out = [];
  let depth = 0;
  let cur = '';
  for (const ch of text) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  out.push(cur.trim());
  return out;
}
/** A text or fill token in one mode → { base: palette colour token, alpha }, following var(), light-dark() and
 *  color-mix(in srgb, var(--x) N%, transparent) the way tokens.css writes them. */
function mixOf(name, m, table) {
  const value = table[name];
  if (value === undefined) {
    if (PALETTE_TOKENS.includes(name)) return { base: name, alpha: 1 };
    throw new Error(`tokens.css: ${name} is not declared`);
  }
  return mixValue(value, m, table);
}
function mixValue(value, m, table) {
  let mm;
  if ((mm = value.match(/^var\((--fd-[\w-]+)\)$/))) return mixOf(mm[1], m, table);
  if ((mm = value.match(/^light-dark\((.*)\)$/))) return mixValue(args(mm[1])[m], m, table);
  if ((mm = value.match(/^color-mix\(in srgb, var\((--fd-[\w-]+)\) ([\d.]+)%, transparent\)$/))) {
    const inner = mixOf(mm[1], m, table);
    return { base: inner.base, alpha: inner.alpha * Number(mm[2]) / 100 };
  }
  throw new Error(`tokens.css: cannot resolve "${value}"`);
}
/* The text ladder as tokens.css declares it, resolved per mode: the rules measure this, and palette-rules.js keeps
   a copy for the browser (theme.js), which must not drift from it. */
const ladderOf = (table) => Object.fromEntries(TEXT_STEPS.map((s) => {
  const [l, d] = [0, 1].map((m) => mixOf(s, m, table));
  return [s, { base: l.base, alpha: [l.alpha, d.alpha] }];
}));
const LADDER_RESOLVED = (() => {
  const [l, d] = [0, 1].map((m) => mixOf('--fd-fill', m, LADDER));
  return { fill: { base: l.base, alpha: [l.alpha, d.alpha] }, default: ladderOf(LADDER), high: ladderOf({ ...LADDER, ...HIGH }) };
})();
const plain = (o) => JSON.parse(JSON.stringify(o));
const checkText = (tokens, name, context = '') => rules.checkText(tokens, name, context, fail, { ladder: LADDER_RESOLVED });
const measure = (tokens, name, context) => rules.measure(tokens, name, context, fail);

function check() {
  // 0. palette-rules.js mixes the text steps exactly as tokens.css does.
  if (JSON.stringify(plain(TEXT_LADDER)) !== JSON.stringify(plain(LADDER_RESOLVED))) fail(`fire/js/palette-rules.js TEXT_LADDER differs from tokens.css: ${JSON.stringify(LADDER_RESOLVED)}`);

  // 1. Ember equals the literals in tokens.css.
  const rootTokens = { ...decls(block(':root')), ...decls(block(':root, [data-accent="ember"]')) };
  const ember = PALETTES.find((p) => p.name === 'ember');
  for (const key of PALETTE_TOKENS) {
    const ours = cssValue(ember.tokens[key]);
    if (rootTokens[key] !== ours) fail(`ember ${key}: engine "${ours}" ≠ tokens.css "${rootTokens[key]}"`);
  }
  for (const key of CONTRAST_TOKENS) {
    const ours = cssValue(ember.contrast[key]);
    if (HIGH[key] !== ours) fail(`ember high-contrast ${key}: engine "${ours}" ≠ tokens.css "${HIGH[key]}"`);
  }

  // 2. A zero tone is the identity, for every palette.
  for (const p of PALETTES) {
    const toned = toneTokens(p.tokens, TONE_DEFAULT);
    for (const key of PALETTE_TOKENS) {
      if (toned[key][0] !== p.tokens[key][0] || toned[key][1] !== p.tokens[key][1]) fail(`${p.name}: toneTokens(TONE_DEFAULT) changed ${key}`);
    }
  }

  // 3. The table.
  const head = 'palette    mode   bg       accent   text     label    focus    text/bg text/sf /wash  label  /hover ink   focus hover';
  console.log(`\n${head}\n${'-'.repeat(head.length)}`);
  for (const p of PALETTES) {
    const rows = measure(p.tokens, p.name, '');
    rows.forEach((row, m) => {
      const v = (k) => p.tokens[k][m];
      console.log(`${(m ? '' : p.name).padEnd(10)} ${row.mode.padEnd(6)} ${v('--fd-bg')}  ${v('--fd-accent')}  ${v('--fd-accent-text')}  ${v('--fd-accent-contrast')}  ${v('--fd-focus')}  ${r2(row.textBg)}  ${r2(row.textSurface)}  ${r2(row.textWash)}  ${r2(row.label)}  ${r2(row.labelHover)} ${r2(row.ink)} ${r2(row.focus)}  ${row.hoverDL >= 0 ? '+' : ''}${row.hoverDL.toFixed(3)}`);
      // The ring is the accent wherever the accent reaches 3:1, and falls back only when it does not.
      const want = engine.focusOf(v('--fd-accent'), v('--fd-accent-text'), v('--fd-ink'), engine.focusGrounds(p.tokens, m));
      if (v('--fd-focus') !== want) fail(`${p.name} ${row.mode}: --fd-focus ${v('--fd-focus')} is not focusOf() ${want}`);
    });
    // Neutral chroma, so "tinted, not grey" is visible at a glance.
    const chroma = (k, m) => toOklch(parse(p.tokens[k][m]).rgb)[1].toFixed(3);
    console.log(`${''.padEnd(10)} chroma bg ${chroma('--fd-bg', 0)}/${chroma('--fd-bg', 1)} · surface ${chroma('--fd-surface', 0)}/${chroma('--fd-surface', 1)} · line ${chroma('--fd-line', 0)}/${chroma('--fd-line', 1)} · ink ${chroma('--fd-ink', 0)}/${chroma('--fd-ink', 1)}`);
  }

  // 4. Text steps: the worst ratio of each step over bg, sunken, surface, raised and the fill on each.
  const alphas = (level) => [0, 1].map((m) => TEXT_STEPS.slice(1).map((s) => `${Math.round(mixOf(s, m, level === 'high' ? { ...LADDER, ...HIGH } : LADDER).alpha * 100)}`).join('/')).join(' · ');
  console.log(`\ntext steps, worst ratio over bg · sunken · surface · raised, --fd-fill on each, --fd-accent-8 on bg and surface (want text–text-3 ≥ ${TEXT_MIN}, text-4 ≥ ${FAINT_MIN})`);
  console.log(`ink alpha of text-2/3/4, light · dark: default ${alphas('default')}; high ${alphas('high')}`);
  const thead = 'palette    mode   default: text  t-2   t-3   t-4  | high: text  t-2   t-3   t-4  | t-3 worst on';
  console.log(`${thead}\n${'-'.repeat(thead.length)}`);
  for (const p of PALETTES) {
    // High contrast changes the text steps (read from tokens.css) and the lines; the backgrounds stay.
    checkText(p.tokens, p.name).forEach((row, m) => {
      const cells = (t) => TEXT_STEPS.map((s) => r2(t[s].worst)).join(' ');
      console.log(`${(m ? '' : p.name).padEnd(10)} ${(m ? 'dark' : 'light').padEnd(6)}          ${cells(row.default)}  |       ${cells(row.high)}  | ${row.default['--fd-text-3'].where}`);
    });
  }

  // 5. The [data-accent] blocks of tokens.css: label on the fill, and accent text on every palette's page and surface.
  const accentRows = [];
  for (const [selector, body] of RULES) {
    const mm = selector.match(/\[data-accent="([\w-]+)"\]$/);
    if (!mm) continue;
    const d = decls(body);
    const pairOf = (value) => { const lm = value.match(/^light-dark\((.*)\)$/); return lm ? args(lm[1]) : [value, value]; };
    const accent = pairOf(d['--fd-accent']);
    const hover = pairOf(d['--fd-accent-hover']);
    const label = pairOf(d['--fd-accent-contrast']);
    const text = pairOf(d['--fd-accent-text']);
    if (!d['--fd-focus']) fail(`[data-accent="${mm[1]}"]: --fd-focus must be declared (the ring follows the accent)`);
    const focus = pairOf(d['--fd-focus'] ?? d['--fd-accent']);
    const cells = [];
    for (const m of [0, 1]) {
      const mode = m === 0 ? 'light' : 'dark';
      const lc = contrast(label[m], accent[m]);
      const lh = contrast(label[m], hover[m]);
      if (lc < TEXT_MIN) fail(`[data-accent="${mm[1]}"] ${mode}: label on accent ${lc.toFixed(2)} < ${TEXT_MIN}`);
      if (lh < TEXT_MIN) fail(`[data-accent="${mm[1]}"] ${mode}: label on accent-hover ${lh.toFixed(2)} < ${TEXT_MIN}`);
      const dL = L(hover[m]) - L(accent[m]);
      if (L(label[m]) > 0.6 ? dL >= 0 : dL <= 0) fail(`[data-accent="${mm[1]}"] ${mode}: accent-hover moves toward its label (${dL.toFixed(3)})`);
      let worst = Infinity;
      for (const p of PALETTES) {
        for (const k of ['--fd-bg', '--fd-surface']) {
          worst = Math.min(worst, contrast(text[m], p.tokens[k][m]), contrast(text[m], washOver(accent[m], p.tokens[k][m])));
        }
      }
      if (worst < TEXT_MIN) fail(`[data-accent="${mm[1]}"] ${mode}: accent-text ${worst.toFixed(2)} on a palette's page or surface (or the accent wash on it) < ${TEXT_MIN}`);
      const ring = Math.min(...PALETTES.flatMap((p) => engine.focusGrounds({ ...p.tokens, '--fd-accent': accent }, m).map((g) => contrast(focus[m], g))));
      if (ring < rules.FOCUS_MIN) fail(`[data-accent="${mm[1]}"] ${mode}: --fd-focus ${ring.toFixed(2)} on a palette's page, well or surface < ${rules.FOCUS_MIN}`);
      cells.push(`${mode} label ${lc.toFixed(2)}/${lh.toFixed(2)} text ${worst.toFixed(2)} ring ${ring.toFixed(2)}`);
    }
    accentRows.push(`${mm[1]}: ${cells.join(', ')}`);
  }
  console.log(`\n[data-accent] blocks (accent text: worst over every palette's page and surface and the wash on them): ${accentRows.join(' · ')}`);

  // 6. Status fills that carry text: each tone's label on its fill, on :root and on any other block that sets them.
  const TONES = ['success', 'warning', 'danger', 'info', 'violet'];
  const root = decls(block(':root'));
  const pairOfValue = (value, table) => {
    const vm = value.match(/^var\((--fd-[\w-]+)\)$/);
    if (vm) {
      if (!table[vm[1]]) throw new Error(`tokens.css: ${vm[1]} is not declared`);
      return pairOfValue(table[vm[1]], table);
    }
    const lm = value.match(/^light-dark\((.*)\)$/);
    return lm ? args(lm[1]) : [value, value];
  };
  const toneRows = [];
  const toneBlocks = RULES.filter(([sel, body]) => sel === ':root' || TONES.some((t) => new RegExp(`--fd-${t}-(fill|contrast)\\s*:`).test(body)));
  const selectors = [...new Set(toneBlocks.map(([sel]) => sel))];
  for (const sel of selectors) {
    const table = { ...root, ...decls(block(sel)) };
    for (const tone of TONES) {
      const fillKey = `--fd-${tone}-fill`;
      const labelKey = `--fd-${tone}-contrast`;
      if (!table[fillKey] || !table[labelKey]) { fail(`tokens.css ${sel}: ${fillKey} and ${labelKey} must both be declared`); continue; }
      const fill = pairOfValue(table[fillKey], table);
      const label = pairOfValue(table[labelKey], table);
      const ratios = [0, 1].map((m) => contrast(label[m], fill[m]));
      ratios.forEach((r, m) => { if (r < TEXT_MIN) fail(`${sel} ${m ? 'dark' : 'light'}: ${labelKey} on ${fillKey} ${r.toFixed(2)} < ${TEXT_MIN}`); });
      if (sel === ':root') toneRows.push(`${tone} ${fill[0]}/${fill[1]} ${label[0] === label[1] ? label[0] : label.join('/')} ${ratios.map((r) => r.toFixed(2)).join('/')}`);
    }
  }
  console.log(`\nstatus fills that carry text (fill light/dark, label, ratio light/dark): ${toneRows.join(' · ')}`);

  // 7. Tone sweep: extreme and mixed tones on every palette, in both contrast levels, must still meet the rules.
  const tones = [];
  for (const hue of [-180, -90, -24, 0, 45, 120, 180]) for (const vivid of [0, 60, 100, 150]) for (const light of [-12, 0, 12]) for (const warmth of [-100, 0, 100]) tones.push({ hue, vivid, light, warmth });
  let swept = 0;
  for (const p of PALETTES) {
    for (const level of ['default', 'high']) {
      const base = engine.paletteTokens(p.name, { contrast: level });
      for (const tone of tones) {
        if (Object.keys(TONE_DEFAULT).every((k) => tone[k] === TONE_DEFAULT[k])) continue;
        const toned = toneTokens(base, tone);
        const context = `tone ${JSON.stringify(tone)}${level === 'high' ? ', high contrast' : ''}`;
        measure(toned, p.name, context);
        // The text steps (both levels) do not depend on the high-contrast lines, so once per tone is enough.
        if (level === 'default') checkText(toned, p.name, `tone ${JSON.stringify(tone)}`);
        swept++;
      }
    }
  }
  // Warmth ±100 stays a neutral-looking page: the page chroma it adds is about .018 in light mode.
  const warmthReport = [];
  for (const p of PALETTES) {
    for (const w of [-100, 100]) {
      const t = toneTokens(p.tokens, { ...TONE_DEFAULT, warmth: w });
      const [, a0, b0] = labOf(p.tokens['--fd-bg'][0]);
      const [, a1, b1] = labOf(t['--fd-bg'][0]);
      const added = Math.hypot(a1 - a0, b1 - b0);
      // Blue near white is gamut-limited (about .009–.013 at the page's L); yellow-orange reaches about .018.
      const min = w > 0 ? 0.013 : 0.008;
      // A page that is already as tinted as sRGB allows at its lightness (iris or midnight cooled further) passes.
      const [Lr, Cr, hr] = toOklch(parse(t['--fd-bg'][0]).rgb);
      const atLimit = Cr >= 0.9 * toOklch(parse(engine.oklch(Lr, 0.2, hr)).rgb)[1];
      if ((added < min && !atLimit) || added > 0.024) fail(`${p.name}: warmth ${w} adds ${added.toFixed(4)} chroma to the light page (want ${min}–.024)`);
      warmthReport.push(`${p.name} ${w > 0 ? '+' : ''}${w}: ${added.toFixed(4)}${added < min ? ' (sRGB limit)' : ''}`);
    }
  }
  console.log(`\nwarmth ±100, chroma added to the light page: ${warmthReport.join(' · ')}`);
  console.log(`\ntone sweep: ${swept} toned maps checked (${tones.length - 1} tones × ${PALETTES.length} palettes × 2 contrast levels)`);

  checkStructure();
  checkLooks();

  if (errors.length) {
    console.error(`\nFAILED: ${errors.length} violation(s)\n${errors.slice(0, 60).map((e) => `  ✗ ${e}`).join('\n')}${errors.length > 60 ? `\n  … and ${errors.length - 60} more` : ''}`);
    process.exitCode = 1;
  } else {
    console.log('\nok: every rule holds; ember matches tokens.css; a zero tone is the identity.');
  }
}

/* ---------- 8. The structural dials (tokens.css, data-surfaces and data-controls) ----------
   Every palette, light and dark, default and high contrast, under every surfaces value combined with every controls
   value: the text steps on every ground the pair makes (page, sunken, surface, raised; the neutral fill, the field,
   the head strip and the control's rest and hover fills on each), accent text on the page and surface; the control
   edges the outlined values draw (an input's under outlined surfaces, a secondary control's under outlined controls)
   at 3:1 on every ground; and the focus ring: its accent band against the page-coloured gap and against the surface
   it sits on, never lower than under the default surfaces (and at 3:1 wherever the default reaches it). Elevation and
   headings change no colour. The values are read from tokens.css, so the check follows the CSS. */
/* surfaces: the element with the attribute names the pair it was given, its children take the new pair from those
   names (tokens.css says why); controls: one block. */
const STRUCTURE_SELECTORS = {
  surfaces: (v) => [`[data-surfaces="${v}"], [data-surfaces="${v}"] [data-palette]`, `[data-surfaces="${v}"] > *, [data-surfaces="${v}"] [data-palette] > *`],
  controls: (v) => [`[data-controls="${v}"], [data-controls="${v}"] [data-palette]`],
};
const blockOr = (selectors) => Object.assign({}, ...selectors.map((sel) => (RULES.some(([s]) => s === sel) ? decls(block(sel)) : {})));
/** A colour token in one mode, over a palette map: { hex } when opaque, { base, alpha } when a wash, null when transparent. */
function layerOf(value, m, tokens, table) {
  let mm;
  if (value === 'transparent') return null;
  if ((mm = value.match(/^var\((--fd-[\w-]+)\)$/))) {
    const name = mm[1];
    if (name in table) return layerOf(table[name], m, tokens, table);
    if (tokens[name]) return { hex: tokens[name][m] };
    throw new Error(`structure check: ${name} is not declared`);
  }
  if ((mm = value.match(/^light-dark\((.*)\)$/))) return layerOf(args(mm[1])[m], m, tokens, table);
  if ((mm = value.match(/^color-mix\(in srgb, var\((--fd-[\w-]+)\) ([\d.]+)%, transparent\)$/))) {
    const inner = layerOf(`var(${mm[1]})`, m, tokens, table);
    return inner.hex ? { base: inner.hex, alpha: Number(mm[2]) / 100 } : { base: inner.base, alpha: inner.alpha * Number(mm[2]) / 100 };
  }
  if ((mm = value.match(/^color-mix\(in srgb, var\((--fd-[\w-]+)\) ([\d.]+)%, var\((--fd-[\w-]+)\)\)$/))) {
    const a = layerOf(`var(${mm[1]})`, m, tokens, table);
    const b = layerOf(`var(${mm[3]})`, m, tokens, table);
    return { hex: rules.over(a.hex ?? a.base, (a.alpha ?? 1) * Number(mm[2]) / 100, b.hex) };
  }
  throw new Error(`structure check: cannot resolve "${value}"`);
}
const onto = (layer, ground) => (layer === null ? ground : layer.hex ?? rules.over(layer.base, layer.alpha, ground));

const SURFACES = ['objects', 'flat', 'outlined'];
const CONTROLS = ['soft', 'outlined', 'filled'];
/** Every palette × contrast level × surfaces × controls, or the cases given: [{ p: { name }, level, base, surfaces, controls }]. */
function structureCases() {
  const out = [];
  for (const p of PALETTES) {
    for (const level of ['default', 'high']) {
      const base = engine.paletteTokens(p.name, { contrast: level });
      for (const surfaces of SURFACES) for (const controls of CONTROLS) out.push({ p, level, base, surfaces, controls });
    }
  }
  return out;
}
function checkStructure(cases = structureCases(), title = `${PALETTES.length} palettes × 2 modes × 2 contrast levels × ${SURFACES.length} surfaces × ${CONTROLS.length} controls`) {
  const worst = {};
  const note = (key, value, where) => { if (!worst[key] || value < worst[key].value) worst[key] = { value, where }; };
  let maps = 0;
  for (const { p, level, base, surfaces, controls } of cases) {
    {
      const ladder = level === 'high' ? { ...LADDER, ...HIGH } : LADDER;
      {
        const sTable = { ...ladder, ...blockOr(STRUCTURE_SELECTORS.surfaces(surfaces)) };
        {
          const table = { ...sTable, ...blockOr(STRUCTURE_SELECTORS.controls(controls)) };
          // The surface pair the value makes, as the browser resolves it on <html>.
          const tokens = { ...base };
          // Both are resolved against the pair the parent gave (the names hold it), as the browser does one element down.
          const parent = Object.fromEntries(Object.entries(table).filter(([k]) => k !== '--fd-bg' && k !== '--fd-surface'));
          for (const key of ['--fd-bg', '--fd-surface']) {
            if (key in table) tokens[key] = [0, 1].map((m) => layerOf(table[key], m, base, parent).hex);
          }
          for (const m of [0, 1]) {
            const mode = m ? 'dark' : 'light';
            const where = `${p.name} ${mode}${level === 'high' ? ' high contrast' : ''} surfaces=${surfaces} controls=${controls}`;
            const v = (k) => tokens[k][m];
            const lay = (name) => layerOf(`var(${name})`, m, tokens, parent);
            const grounds = [];
            for (const b of rules.BASES) {
              const g = v(b);
              const short = rules.BASE_SHORT[b];
              grounds.push([short, g]);
              for (const name of ['--fd-fill', '--fd-field', '--fd-field-hover', '--fd-control-bg', '--fd-control-bg-hover']) {
                const l = lay(name);
                if (l && !l.hex) grounds.push([`${name.slice(5)}/${short}`, onto(l, g)]);
              }
            }
            for (const name of ['--fd-field', '--fd-field-hover', '--fd-surface-head']) {
              const l = lay(name);
              if (l?.hex && !grounds.some(([, g]) => g === l.hex)) grounds.push([name.slice(5), l.hex]);
            }
            for (const s of TEXT_STEPS) {
              const step = LADDER_RESOLVED[level][s];
              const min = s === '--fd-text-4' ? FAINT_MIN : TEXT_MIN;
              for (const [label, g] of grounds) {
                const c = contrast(rules.over(v(step.base), step.alpha[m], g), g);
                note(`${s}${s === '--fd-text-4' ? ' (3:1)' : ''}`, c, `${where} on ${label}`);
                if (c < min) fail(`${where}: ${s} ${c.toFixed(2)} on ${label} < ${min}`);
              }
            }
            for (const k of ['--fd-bg', '--fd-surface']) {
              for (const g of [v(k), washOver(v('--fd-accent'), v(k))]) {
                const c = contrast(v('--fd-accent-text'), g);
                note('--fd-accent-text', c, `${where} on ${k.slice(5)}`);
                if (c < TEXT_MIN) fail(`${where}: accent-text ${c.toFixed(2)} on ${k.slice(5)} < ${TEXT_MIN}`);
              }
            }
            // Edges that identify a control: 3:1 against every ground the control can sit on.
            for (const [name, on] of [['--fd-control-line', surfaces === 'outlined'], ['--fd-control-edge', controls === 'outlined']]) {
              if (!on) continue;
              const l = lay(name);
              for (const [label, g] of grounds.filter(([label]) => !label.includes('/') || label.startsWith('fill/'))) {
                const c = contrast(onto(l, g), g);
                note(`${name} (3:1, outlined)`, c, `${where} on ${label}`);
                if (c < NONTEXT_MIN) fail(`${where}: ${name} ${c.toFixed(2)} on ${label} < ${NONTEXT_MIN}`);
              }
            }
            // Focus: the ring's band (--fd-focus) against the page-coloured gap and the surface the control sits on,
            // at 3:1 under every surfaces value.
            if (controls === 'soft') {
              const ring = Math.min(contrast(v('--fd-focus'), v('--fd-bg')), contrast(v('--fd-focus'), v('--fd-surface')));
              note('focus ring (3:1)', ring, where);
              if (ring < NONTEXT_MIN) fail(`${where}: the focus ring reaches ${ring.toFixed(2)}:1 on the page or a surface < ${NONTEXT_MIN}`);
            }
            maps++;
          }
        }
      }
    }
  }
  console.log(`\nstructural dials: ${maps} maps (${title}); worst ratio per rule:`);
  for (const [key, { value, where }] of Object.entries(worst)) console.log(`  ${key.padEnd(34)} ${value.toFixed(2)}  ${where}`);
}
const NONTEXT_MIN = 3;

/* ---------- 9. The named looks (contract/looks/named) ----------
   Each look's palette, toned as the look tones it and at its own contrast level, through every palette rule, then
   through the structural check under the look's own surfaces and controls. */
function checkLooks() {
  const dir = path.join(ROOT, 'contract/looks/named');
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort() : [];
  const cases = [];
  const rows = [];
  for (const f of files) {
    const { name, record } = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    if (typeof record.palette !== 'string') { fail(`look ${name}: the palette must be a preset name (the Tweaks panel holds it whole)`); continue; }
    const level = record.dials?.contrast === 'high' ? 'high' : 'default';
    const tokens = toneTokens(engine.paletteTokens(record.palette, { contrast: level }), { ...TONE_DEFAULT, ...(record.tone || {}) });
    const label = `look ${name} (${record.palette})`;
    const before = errors.length;
    measure(tokens, label, 'look');
    checkText(tokens, label, 'look');
    const surfaces = record.dials?.surfaces ?? 'objects';
    const controls = record.dials?.controls ?? 'soft';
    // The structural check measures the ring under the soft controls only; a look's ring is the same token.
    cases.push({ p: { name: label }, level, base: tokens, surfaces, controls });
    if (controls !== 'soft') cases.push({ p: { name: `${label} ring` }, level, base: tokens, surfaces, controls: 'soft' });
    rows.push(`${name} ${record.palette}${level === 'high' ? ' high' : ''} ${surfaces}/${controls}${errors.length > before ? ' FAILS' : ''}`);
  }
  console.log(`\nnamed looks: ${rows.join(' · ')}`);
  checkStructure(cases, `${files.length} named looks under their own surfaces and controls`);
}

function labOf(hex) {
  const [Lv, C, h] = toOklch(parse(hex).rgb);
  return [Lv, C * Math.cos((h * Math.PI) / 180), C * Math.sin((h * Math.PI) / 180)];
}

