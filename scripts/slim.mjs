#!/usr/bin/env node
/*
 * fire slim: writes a Fire trimmed to what a product uses: one stylesheet, one behaviour entry, the font files of its
 * type set, and a report of what was kept and why.
 *
 *   fire slim <sources…> --out <dir> [--theme theme.json] [--include a,b] [--level family|component] [--report]
 *   fire slim … --check            fail when the files in --out are stale for the current sources (CI)
 *   fire slim --verify <build dir> fail when a production build still holds a rule or a module the report dropped,
 *                                  and print the sizes before and after
 *
 * Runs in any project that installs Fire; it needs only Node and Fire's own files. With no sources, the settings come
 * from `"fire": { "slim": { "sources", "out", "theme", "include", "level" } }` in the nearest package.json.
 *
 * Sources: what lint-markup reads (.html, .jsx/.tsx, .vue, html`…` in .ts/.js), with its tokeniser, plus every string
 * literal in code and the <script> blocks of .html and .vue files. Out (default .fire-slim):
 *   fire.css    tokens, the palette, the type set, base, the components, layout: Fire's cascade order
 *   fire.js     imports and initialises only the behaviour modules kept; the same init() and ready behaviour as
 *               fire/fire.js and explicit named exports, so importing a dropped module's namespace fails the build
 *   fonts/      the font files the kept @font-face rules name (with --theme, the theme's type set only)
 *   slim.json   the report: each component, stylesheet, module, palette, type set and font kept, with the file and
 *               line that first needed it; what was dropped; sizes before and after (raw and gzip)
 *
 * How it decides (the dependency map is contract/slim-map.json, generated by scripts/build-slim-map.mjs):
 *   - a component is used when its fd- class, its element (<fd-chart>, <FireChart>) or a data-fd-* attribute its
 *     module handles is in the source; a name imported from fire-design (named, namespace or import()) keeps its
 *     module; --include keeps components, modules or whole stylesheets (`charts`, `site`) by name;
 *   - a kept module keeps the modules it imports and every component its code names (what it builds at run time),
 *     and a kept component keeps its behaviour module, until nothing changes;
 *   - CSS: a selector can still match when every fd- class and tag it requires is kept and its data-fd-* attributes
 *     occur in the source or a kept module (:not() never requires; :is(), :where() and :has() need one argument).
 *     `family` keeps each component stylesheet whole when one of its selectors can match; `component` also removes
 *     the selectors and rules that cannot, walking @media, @container, @supports and @layer and dropping them when
 *     empty. Tokens, base and layout are kept, and so are rules that require no Fire class. Classes the catalogue
 *     does not list count as present. @keyframes, @property and custom-property blocks of a dropped part stay when
 *     something kept refers to them;
 *   - --theme: only the record's palette (the palettes.css rule, or themeToCss's tokens for a toned or custom
 *     palette) and type set, plus any data-palette / data-type the source writes; @font-face rules for the families
 *     left; at `component`, dial values (data-density="compact" …) that neither the record, the source nor a kept
 *     module can set. A product with the Tweaks panel keeps every palette, type set and dial.
 * Fire is read when it is imported by the package name or by a path whose last segments are fire/fire.js (all of Fire)
 * or fire/js/<name>.js (one module, which is kept): static imports, import('…'), re-exports and namespace imports read
 * through members (F.tweaks.open()). By path, a namespace or default import used where no member can be read, or an
 * import() whose result is not taken apart in place, keeps every module, and slim.json says where (loadedBy). A
 * <script src=".../fire/fire.js"> tag changes nothing (the markup decides) and is listed. A product that loads Fire by
 * path must point that path at this output (replace the folder it names, or alias it) for the build to use it.
 * Class names built at run time from strings no scan can read (`fd-badge-${tone}`, className={cls}) are listed in
 * the report with file and line; keep what they make with --include.
 * It does not rewrite markup, split per route, or minify: the bundler does the last.
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { scanSource, kindOf, expandInputs, HOLE } from './lint-markup.mjs';
import { splitCss, selectorsOf, needs, canMatch } from './lib/slim-css.mjs';

const FIRE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const readFire = (f) => fs.readFileSync(path.join(FIRE, f), 'utf8');
const DIALS = ['data-density', 'data-text-size', 'data-contrast', 'data-surfaces', 'data-elevation', 'data-controls', 'data-headings',
  'data-imagery', 'data-heading-case', 'data-figures', 'data-signature-field', 'data-signature-mark', 'data-signature-cell',
  'data-signature-ramp', 'data-signature-marks', 'data-signature-intensity'];
const TRACKED = (name) => name.startsWith('data-fd-') || /^data-(?:[\w-]+-)?shell$/.test(name) || name === 'data-only' || name === 'data-doc-show';
// A module specifier that is Fire: the package (`fire-design`), or a path whose last segments are fire/fire.js (all of
// Fire) or fire/js/<name>.js (one module). Returns { kind: 'package' | 'path', mod: the one module, or null }.
const SPEC = (s) => {
  if (s === 'fire-design' || s === 'fire-design/fire/fire.js') return { kind: 'package', mod: null };
  const p = !s.startsWith('fire-design/') && /(?:^|\/)fire\/(?:fire|js\/([\w-]+))\.js$/.exec(s.replace(/[?#].*$/, ''));
  return p ? { kind: 'path', mod: p[1] || null } : null;
};
const camel = (attr) => attr.replace(/^data-/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const size = (buf) => ({ raw: buf.length, gzip: zlib.gzipSync(buf, { level: 9 }).length });

/* ------------------------------------------------------------------ reading the product */

export function scan(files, { map, catalog, cwd = process.cwd() }) {
  const classOf = new Map(Object.entries(catalog.classes));
  const tagOf = new Map(catalog.components.filter((c) => c.element).map((c) => [c.element, c.id]));
  const found = { components: new Map(), modules: new Map(), attributes: new Map(), names: new Map(), dynamic: [], unknown: [],
    text: '', elements: false, loaded: { package: new Set(), path: new Set(), tags: [], unresolved: [] } };
  const first = (m, key, where) => { if (!m.has(key)) m.set(key, where); };
  const attr = (name, value, where) => {
    const a = found.attributes.get(name) ?? { values: new Set(), any: false, where };
    if (value === null) a.any = true; else a.values.add(value);
    found.attributes.set(name, a);
  };
  const useClass = (k, where) => {
    if (classOf.has(k)) first(found.components, classOf.get(k), `${where} (.${k})`);
    else if (tagOf.has(k)) first(found.components, tagOf.get(k), `${where} (<${k}>)`);
  };
  const usePrefix = (p, where) => { for (const k of classOf.keys()) if (k.startsWith(p)) useClass(k, where); };
  for (const file of files) {
    const text = fs.readFileSync(file, 'utf8');
    const rel = path.relative(cwd, file) || file;
    const starts = [0];
    for (let i = 0; i < text.length; i++) if (text[i] === '\n') starts.push(i + 1);
    const at = (p) => { let lo = 0, hi = starts.length - 1; while (lo < hi) { const mid = (lo + hi + 1) >> 1; if (starts[mid] <= p) lo = mid; else hi = mid - 1; } return `${rel}:${lo + 1}`; };
    found.text += '\n' + text;
    const kind = kindOf(file);
    const parts = [[kind, text, 0]];
    if (kind === 'html' || kind === 'vue') {
      for (const m of text.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
        const src = /\bsrc\s*=\s*["']?([^"'\s>]+)/i.exec(m[1])?.[1];
        if (src && SPEC(src)?.kind === 'path') { found.loaded.path.add(src); found.loaded.tags.push({ at: at(m.index), src }); }
        if (/type\s*=\s*["']?(?:application\/(?:ld\+)?json|importmap)/i.test(m[1])) continue;
        parts.push([/lang\s*=\s*["']?[jt]sx/.test(m[1]) ? 'jsx' : 'lit', m[2], m.index + m[0].indexOf('>') + 1]);
      }
    }
    for (const [k, src, base] of parts) {
      const { events, strings } = scanSource(src, k);
      for (const ev of events) {
        if (ev.type !== 'open') continue;
        const where = at(base + ev.at);
        const tag = ev.tag.toLowerCase();
        if (tagOf.has(tag)) first(found.components, tagOf.get(tag), `${where} (<${tag}>)`);
        if (map.wrappers[ev.tag]) first(found.components, tagOf.get(map.wrappers[ev.tag]), `${where} (<${ev.tag}>)`);
        for (const a of ev.attrs) {
          if (a.directive) continue;
          const name = a.name.toLowerCase() === 'classname' ? 'class' : a.name.toLowerCase();
          if (name !== 'class') { attr(name, a.dynamic || !a.hasValue ? (a.hasValue ? null : '') : a.value, where); continue; }
          if (a.dynamic && !a.strings.length) found.dynamic.push({ at: at(base + a.at), expr: `${a.name}=…` });
          for (const { s, at: p } of a.strings) {
            for (const t of s.split(/\s+/).filter(Boolean)) {
              if (t.includes(HOLE)) {
                found.dynamic.push({ at: at(base + p), expr: t.replace(/\u0001+/g, '${…}') });
                const pre = t.split(HOLE)[0];
                if (pre.startsWith('fd-')) usePrefix(pre, at(base + p));
              } else if (t.startsWith('fd-')) {
                if (classOf.has(t)) useClass(t, at(base + p)); else found.unknown.push({ at: at(base + p), name: t });
              }
            }
          }
        }
      }
      // Code: every string literal (classList.add('fd-x'), templates that build markup), and the imports.
      for (const s of strings) {
        const where = at(base + s.at);
        for (const m of s.s.matchAll(/(?<![\w-])fd-[a-z0-9][\w-]*/g)) {
          const t = m[0], next = s.s[m.index + t.length];
          if (next === HOLE) { found.dynamic.push({ at: where, expr: s.s.slice(m.index, m.index + t.length + 1).replace(/\u0001/, '${…}') }); usePrefix(t, where); } else useClass(t.replace(/-+$/, ''), where);
        }
        for (const m of s.s.matchAll(/data-fd-[\w-]*[a-z0-9]/g)) attr(m[0], null, where);
      }
      if (k === 'lit' || k === 'jsx') imports(src, base, at, found, map);
    }
  }
  return found;
}

function imports(code, base, at, found, map) {
  const handles = new Set(), pathHandles = new Map();   // names bound to Fire's namespace; those of a path import, where
  const name = (n, where, quiet) => {
    n = n.trim();
    if (!n || /^type\s/.test(n)) return;
    if (!(n in map.exports)) { if (!quiet) found.unknown.push({ at: where, name: `${n} (not an export of fire-design)` }); return; }
    if (!found.names.has(n)) found.names.set(n, where);
    const m = map.exports[n];
    if (map.modules[m]) { if (!found.modules.has(m)) found.modules.set(m, `${where} (${n})`); }
  };
  const list = (clause, where, quiet) => { for (const part of clause.split(',')) name(part.split(/\s+as\s+/)[0], where, quiet); };
  // One module file (/fire/js/tweaks.js) keeps that module; the whole of Fire, by path, is read like the package.
  const seen = (s, spec, where) => {
    found.loaded[s.kind].add(spec);
    if (s.mod && map.modules[s.mod] && !found.modules.has(s.mod)) found.modules.set(s.mod, `${where} (${spec})`);
  };
  const keepAll = (where, spec) => {   // a namespace read where no member can be named: every module stays
    found.loaded.unresolved.push({ at: where, specifier: spec });
    for (const m of Object.keys(map.modules)) if (!found.modules.has(m)) found.modules.set(m, `${where} (Fire's namespace is used where no member can be read)`);
  };
  let fire = false;
  for (const m of code.matchAll(/\bimport\s+(type\s+)?([\w$*{}\s,]*?)\s*from\s*['"]([^'"]+)['"]/g)) {
    if (/^fire-design\/(elements|react)$|\/fire\/elements\.js$/.test(m[3])) found.elements = true;
    if (/^fire-design\/(react|vue)$/.test(m[3])) fire = true;
    const spec = SPEC(m[3]);
    if (m[1] || !spec) continue;
    const where = at(base + m.index);
    seen(spec, m[3], where);
    if (!spec.mod) fire = true;
    const ns = /\*\s*as\s+([\w$]+)/.exec(m[2]);
    const dflt = spec.kind === 'path' && /^\s*([\w$]+)\s*(?:,|$)/.exec(m[2]);
    for (const h of [ns?.[1], dflt?.[1]]) if (h) { handles.add(h); if (spec.kind === 'path' && !spec.mod) pathHandles.set(h, [where, m[3]]); }
    const named = /\{([^}]*)\}/.exec(m[2]);
    if (named) list(named[1], where, !!spec.mod);
  }
  for (const m of code.matchAll(/\bimport\s*['"]([^'"]+)['"]/g)) { const spec = SPEC(m[1]); if (spec) seen(spec, m[1], at(base + m.index)); }
  for (const m of code.matchAll(/\bexport\s+(\*|\{[^}]*\})\s*from\s*['"]([^'"]+)['"]/g)) {
    const spec = SPEC(m[2]);
    if (!spec) continue;
    seen(spec, m[2], at(base + m.index));
    if (m[1] === '*') { if (!spec.mod) for (const n of Object.keys(map.exports)) name(n, at(base + m.index)); } else list(m[1].slice(1, -1), at(base + m.index), !!spec.mod);
  }
  for (const m of code.matchAll(/\bimport\(\s*['"]([^'"]+)['"]\s*\)(?:\s*\.then\(\s*(?:\(\s*\{([^}]*)\}\s*\)|\(?\s*([\w$]+)))?/g)) {
    if (/^fire-design\/elements$|\/fire\/elements\.js$/.test(m[1])) found.elements = true;
    const spec = SPEC(m[1]);
    if (!spec) continue;
    const where = at(base + m.index);
    seen(spec, m[1], where);
    if (spec.mod) continue;
    fire = true;
    if (m[2]) list(m[2], where);
    if (m[3] && !/^(?:function|async)$/.test(m[3])) handles.add(m[3]);
    const before = code.slice(Math.max(0, m.index - 80), m.index);
    const bound = /(?:const|let|var)\s+(?:([\w$]+)|\{([^}]*)\})\s*=\s*await\s*$/.exec(before);
    if (bound?.[1]) handles.add(bound[1]);
    if (bound?.[2]) list(bound[2], where);
    if (spec.kind === 'path') {   // by path, a result that is not taken apart in place has to be followed
      const first = m[3] && !/^(?:function|async)$/.test(m[3]) ? m[3] : bound?.[1];
      if (first) pathHandles.set(first, [where, m[1]]); else if (!m[2] && !bound?.[2]) keepAll(where, m[1]);
    }
  }
  if (!fire && !handles.size) return;
  if (fire) handles.add('fire');   // the usual name for loadFire()'s result, a kit's `fire`, or import('fire-design')
  const h = [...handles].map((x) => x.replace(/\$/g, '\\$')).join('|');
  for (const m of code.matchAll(new RegExp(`(?<![\\w$])(?:${h})\\s*\\??\\.\\s*([A-Za-z_$][\\w$]*)`, 'g'))) if (m[1] in map.exports) name(m[1], at(base + m.index));
  for (const m of code.matchAll(new RegExp(`\\{([^{}]*)\\}\\s*=\\s*(?:await\\s+)?(?:${h})\\b`, 'g'))) list(m[1].replace(/:\s*[\w$]+/g, ''), at(base + m.index));
  for (const [id, [where, spec]] of pathHandles) {   // anything left of the handle besides its binding, member reads and destructuring
    const e = id.replace(/\$/g, '\\$');
    const rest = code.replace(new RegExp(`\\*\\s*as\\s+${e}\\b|(?:const|let|var)\\s+${e}\\s*=\\s*await\\b|\\.then\\(\\s*\\(?\\s*${e}\\b|import\\s+${e}\\s*(?=,|from)|\\{[^{}]*\\}\\s*=\\s*(?:await\\s+)?${e}\\b`, 'g'), ' ')
      .replace(new RegExp(`(?<![\\w$.])${e}\\s*\\??\\.\\s*[A-Za-z_$]`, 'g'), ' ');
    if (new RegExp(`(?<![\\w$.])${e}(?![\\w$])`).test(rest)) keepAll(where, spec);
  }
}

/* ------------------------------------------------------------------ the closure */

export function resolve(found, { map, catalog, include = [] }) {
  const K = new Map(found.components), M = new Map(found.modules);
  for (const [a] of found.attributes) for (const m of map.attributes[a] || []) if (!M.has(m)) M.set(m, `${found.attributes.get(a).where} (${a})`);
  const homes = (file) => Object.entries(map.components).filter(([, c]) => c.home === file).map(([id]) => id);
  for (const name of include) {
    const fam = catalog.components.filter((c) => c.family.toLowerCase() === name.toLowerCase()).map((c) => c.id);
    const sheet = map.css[`components/${name}.css`] ? homes(`components/${name}.css`) : [];
    if (!map.components[name] && !map.modules[name] && !sheet.length && !fam.length) throw new Error(`--include ${name}: not a component, module, stylesheet or family of Fire`);
    if (map.modules[name]) M.set(name, `--include ${name}`);
    for (const id of [...(map.components[name] ? [name] : []), ...sheet, ...fam]) if (!K.has(id)) K.set(id, `--include ${name}`);
  }
  for (const h of Object.values(map.helpers)) for (const id of h.components) if (!K.has(id)) K.set(id, 'built by Fire\'s core');
  for (let changed = true; changed;) {
    changed = false;
    for (const id of K.keys()) for (const m of map.components[id]?.modules || []) if (!M.has(m)) { M.set(m, `behaviour of ${id}`); changed = true; }
    for (const m of [...M.keys()]) {
      for (const i of map.modules[m].imports) if (map.modules[i] && !M.has(i)) { M.set(i, `imported by ${m}`); changed = true; }
      for (const id of map.modules[m].components) if (!K.has(id)) { K.set(id, `built or read by ${m}`); changed = true; }
    }
  }
  const tweaks = K.has('tweaks') || M.has('tweaks');
  return { K, M, tweaks };
}

/* ------------------------------------------------------------------ the stylesheet */

function themeInfo(record, theme) {
  if (!record) return null;
  const { attributes, tokens, faces } = theme.expandTheme(record);
  return { attributes, tokens, faces, css: Object.keys(tokens).some((k) => !/^--fd-(radius-scale|hairline|motion|texture)$/.test(k)) ? theme.themeToCss(record) : '' };
}

export function slimCss({ K, M, tweaks }, found, { map, catalog, level, theme, typeSpec }) {
  const classOf = new Map(Object.entries(catalog.classes));
  const tagOf = new Map(catalog.components.filter((c) => c.element).map((c) => [c.element, c.id]));
  const moduleText = [...M.keys()].map((m) => readFire(map.modules[m].file).replace(/\/\*[\s\S]*?\*\//g, "")).join("\n");   // code, not the headers
  const said = (name) => found.text.includes(name) || moduleText.includes(name) || new RegExp(`dataset\\.${camel(name)}\\b|dataset\\[['"]${camel(name)}`).test(found.text + moduleText);
  const unknown = new Set();
  const variants = new Set(catalog.components.flatMap((c) => [...Object.keys(c.attributes || {}), ...Object.values(c.partAttributes || {}).flatMap(Object.keys)])
    .filter((a) => a.startsWith('data-') && !TRACKED(a) && !DIALS.includes(a) && a !== 'data-palette' && a !== 'data-type'));
  const words = new Map();
  const word = (w) => {  // in the source (comments too) or in kept modules' code (not their comments)
    if (!words.has(w)) words.set(w, new RegExp(`(?<![\\w-])${w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![\\w-])`).test(found.text + moduleText));
    return words.get(w);
  };
  // Live values of the theme's attributes: null = any value may be set.
  const values = (name, themed) => {
    if (!theme || tweaks || !themed) return null;
    const a = found.attributes.get(name);
    // A kept module that writes the attribute (or, for type sets, that imports them) may set any value.
    const writer = (m) => map.modules[m].writes.includes(name === 'data-type' ? 'type-sets' : name);
    if (a?.any || [...M.keys()].some(writer)) return null;
    if (name === 'data-density' && /\bsetDensity\b/.test(found.text)) return null;
    const v = new Set(a?.values || []);
    if (theme.attributes[name]) v.add(theme.attributes[name]);
    return v;
  };
  const live = { 'data-palette': values('data-palette', true), 'data-type': values('data-type', true) };
  for (const d of DIALS) live[d] = values(d, level === 'component');
  const has = (x) => {
    if (typeof x === 'string') {
      const id = x.startsWith('.') ? classOf.get(x.slice(1)) : tagOf.get(x) ?? classOf.get(x);
      if (id === undefined) { unknown.add(x); return true; }
      return K.has(id);
    }
    const v = live[x.name];
    if (v) return x.value === null || x.op !== '=' ? v.size > 0 : v.has(x.value);
    if (TRACKED(x.name)) return said(x.name);
    // A component's own variant value (data-variant="framed"): possible when the word occurs in the source or a
    // kept module, or the source sets that attribute from an expression.
    if (x.op === '=' && x.value && variants.has(x.name)) return found.attributes.get(x.name)?.any || word(x.value);
    return true;
  };
  const anchored = (n) => n.classes.length || n.tags.length || n.groups.length || n.attrs.some((a) => TRACKED(a.name) || live[a.name]);
  const free = (n) => !anchored(n);

  // Core files (tokens, base, layout) and the theme files lose only what the theme rules out; component files at
  // `component` everything that cannot match. Dead rules are always computed, so `fire` says whether a selector
  // with a Fire requirement can still match anywhere in the file.
  const themed = (x) => (typeof x === 'string' ? true : live[x.name] ? has(x) : true);
  function pass(file, mode) {   // mode: 'whole' | 'core' | 'prune'
    const text = readFire(`fire/${file}`);
    const nodes = splitCss(text);
    if (nodes.length !== map.css[file].rules) throw new Error(`contract/slim-map.json is stale for fire/${file}: run node scripts/build-slim-map.mjs`);
    let fire = false;
    const held = [];
    const hold = (src, node, free) => { const k = { src, node, free }; held.push(k); return k; };
    const walk = (list) => list.map((node) => {
      const src = text.slice(node.start, node.end);
      if (node.children) return { prelude: node.prelude, items: walk(node.children) };
      if (node.type === 'stmt') return /^@import/.test(node.prelude) ? '' : src + '\n';
      if (node.type === 'at') return node.name === 'font-face' || (mode === 'prune' && (node.name === 'keyframes' || node.name === 'property')) ? hold(src, node) : src + '\n';
      const sels = selectorsOf(node.prelude);
      const ns = sels.map(needs);
      const ok = sels.filter((x, i) => canMatch(ns[i], has));
      if (ok.some((x) => anchored(needs(x)))) fire = true;
      if (mode === 'whole') return src + '\n';
      const keep = mode === 'core' ? sels.filter((x, i) => canMatch(ns[i], themed)) : ok;
      if (!keep.length) return '';
      if (mode === 'prune' && ns.every(free)) return hold(src, node, true);
      return (keep.length === sels.length ? src : `${keep.join(',\n')} ${text.slice(node.open, node.end)}`) + '\n';
    });
    return { file, out: walk(nodes), fire, held };
  }
  // The text of a pass: strings when the file is kept, held blocks when they are.
  const emit = (items, kept) => items.map((x) => {
    if (typeof x === 'string') return kept ? x : '';
    if (x.items) { const inner = emit(x.items, kept); return inner.trim() ? `${x.prelude} {\n${inner}}\n` : ''; }
    return x.kept ? x.src + '\n' : '';
  }).join('');

  const sheets = [];
  for (const file of map.order) {
    const kind = ['tokens.css', 'base.css', 'layout.css'].includes(file) ? 'core' : ['palettes.css', 'typefaces.css'].includes(file) ? 'theme' : 'component';
    let p = pass(file, kind === 'component' ? 'prune' : 'core');
    p.kept = kind !== 'component' || p.fire;
    if (kind === 'component' && level === 'family' && p.kept) p = { ...pass(file, 'whole'), kept: true };
    sheets.push(Object.assign(p, { kind }));
  }
  // The fonts: with a theme, the families its type set and the kept type-set rules name; else every family.
  const families = new Set();
  const collect = (css) => { for (const m of css.matchAll(/--fd-font-(?:display|sans|mono)\s*:\s*([^;]+)/g)) for (const f of m[1].matchAll(/"([^"]+)"/g)) families.add(f[1]); };
  if (theme && !tweaks) {
    collect(emit(sheets.find((x) => x.file === 'typefaces.css').out, true));
    typeSpec.forEach((f) => families.add(f));
    collect(Object.entries(theme.tokens).map(([k, v]) => `${k}: ${v};`).join(''));
  }
  // Held blocks (@font-face, and at `prune` @keyframes, @property and rules that require no Fire class): kept when
  // something kept names what they define. A requirement-free rule in a kept file that sets more than custom
  // properties is kept as it is.
  const extra = found.text + moduleText;
  for (let round = 0, before = -1; round < 8; round++) {
    const refs = extra + sheets.map((x) => emit(x.out, x.kept)).join('');
    let n = 0;
    for (const sh of sheets) for (const k of sh.held) {
      const name = k.node.prelude.split(/\s+/)[1];
      if (k.node.name === 'font-face') {
        const fam = /font-family\s*:\s*"([^"]+)"/.exec(k.src)?.[1]?.replace(/ Fallback$/, '');
        k.kept = !(theme && !tweaks) || families.has(fam);
      } else if (k.node.name === 'keyframes') k.kept = new RegExp(`(?<![\\w-])${name}(?![\\w-])`).test(k.kept ? refs.replace(k.src, '') : refs);
      else if (k.node.name === 'property') k.kept = refs.includes(`var(${name}`) || extra.includes(name);
      else {
        const body = k.src.slice(k.src.indexOf('{'));
        const defs = [...body.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1]);
        const plain = /(?:^|[;{])\s*(?!--)[a-z-]+\s*:/.test(body);
        k.kept = (sh.kept && (plain || !defs.length)) || defs.some((d) => refs.includes(`var(${d}`) || extra.includes(d));
      }
      if (k.kept) n++;
    }
    if (n === before) break;
    before = n;
  }
  const parts = [], fonts = new Set();
  for (const sh of sheets) {
    let css = emit(sh.out, sh.kept);
    css = css.replace(/url\(\s*["']?\.\/fonts\/([^"')]+)["']?\s*\)/g, (_, u) => { fonts.add(u); return `url("./fonts/${u}")`; });
    if (sh.file === 'palettes.css' && theme?.css && !tweaks) css += theme.css;
    if (css.trim()) parts.push(`/* fire/${sh.file} */\n${css}`);
  }
  return { css: parts.join('\n'), sheets, fonts: [...fonts].sort(), unknown: [...unknown].sort(), live, families: [...families].sort() };
}

/* ------------------------------------------------------------------ the entry */

export function slimJs(M, { map, out }) {
  const src = readFire('fire/fire.js');
  // Fire's own module files, never copies, so the bundler shares them with fire-design/elements: by the package's
  // name when the project installs it, else by a relative path (Fire's own tests, a page served as files).
  let prefix;
  for (let d = out; !prefix && path.dirname(d) !== d; d = path.dirname(d)) {
    const pkg = path.join(d, 'node_modules/fire-design');
    if (fs.existsSync(pkg) && fs.realpathSync(pkg) === fs.realpathSync(FIRE)) prefix = 'fire-design/fire/js/';
  }
  if (!prefix) {
    let real = out, rest = '';
    while (!fs.existsSync(real)) { rest = path.join(path.basename(real), rest); real = path.dirname(real); }
    const rel = path.relative(path.join(fs.realpathSync(real), rest), fs.realpathSync(path.join(FIRE, 'fire/js'))).split(path.sep).join('/');
    prefix = rel.startsWith('.') ? `${rel}/` : `./${rel}/`;
  }
  const kept = Object.keys(map.modules).filter((m) => M.has(m));
  const dropped = Object.keys(map.modules).filter((m) => !M.has(m));
  const lines = src.split('\n').filter((l) => {
    const ns = /^import \* as (\w+) from/.exec(l);
    if (ns) return M.has(ns[1]);
    const ex = /^export \{[^}]*\} from '\.\/js\/(\w+)\.js'/.exec(l);
    return !ex || !map.modules[ex[1]] || M.has(ex[1]);
  }).map((l) => {
    if (/^const modules = \{/.test(l)) return `const modules = { ${kept.join(', ')} };`;
    if (/^export \{ [^}]+ \};$/.test(l)) return kept.length ? `export { ${kept.join(', ')} };` : '';
    return l.replaceAll("'./js/", `'${prefix}`);
  });
  const head = [`/* GENERATED by fire slim from the product's sources; do not edit. A drop-in for fire-design's fire/fire.js with the`,
    ` * behaviour modules this product uses: ${kept.join(', ') || 'none'}.`,
    ` * Dropped: ${dropped.join(', ') || 'none'}. Importing one of those (import { charts } from 'fire-design') fails the build:`,
    ` * add it to the sources, or run fire slim with --include <name>. See slim.json for why each module is here. */`];
  return [...head, ...lines.slice(lines.findIndex((l) => l.startsWith('import ')))].join('\n');
}

/* ------------------------------------------------------------------ the command */

function reachable(entries) {
  const seen = new Set();
  const visit = (file) => {
    if (seen.has(file)) return;
    seen.add(file);
    for (const m of fs.readFileSync(file, 'utf8').matchAll(/^(?:import|export)[^;'"]*?from '(\.[^']+)'/gm)) visit(path.resolve(path.dirname(file), m[1]));
  };
  entries.forEach(visit);
  return [...seen];
}

export async function slim(opts) {
  const cwd = opts.cwd || process.cwd();
  const map = JSON.parse(readFire('contract/slim-map.json'));
  const catalog = JSON.parse(readFire('contract/catalog.json'));
  if (map.fire !== catalog.fire) throw new Error('contract/slim-map.json is stale: run node scripts/build-slim-map.mjs');
  const level = opts.level || 'family';
  if (!['family', 'component'].includes(level)) throw new Error(`--level is family or component, not ${level}`);
  const out = path.resolve(cwd, opts.out || '.fire-slim');
  const files = expandInputs(opts.sources, cwd);
  if (!files.length) throw new Error('fire slim: no source files');
  const themeMod = await import(pathToFileURL(path.join(FIRE, 'fire/js/theme.js')).href);
  const record = typeof opts.theme === 'string' ? JSON.parse(fs.readFileSync(path.resolve(cwd, opts.theme), 'utf8')) : opts.theme || null;
  const theme = themeInfo(record, themeMod);
  let typeSpec = [];
  if (record) {
    const { getTypeface } = await import(pathToFileURL(path.join(FIRE, 'fire/js/typefaces.js')).href);
    const spec = typeof record.type === 'object' && record.type ? record.type : getTypeface(record.type || 'geist').spec;
    typeSpec = [spec.display, spec.sans, spec.mono].filter(Boolean);
  }

  const found = scan(files, { map, catalog, cwd });
  const closure = resolve(found, { map, catalog, include: opts.include || [] });
  const css = slimCss(closure, found, { map, catalog, level, theme, typeSpec });
  const js = slimJs(closure.M, { map, out });

  // What fire.js would ship, and what this ships.
  const fullCss = map.order.map((f) => readFire(`fire/${f}`)).join('\n');
  const fullFonts = [...new Set([...fullCss.matchAll(/url\(\s*["']?\.\/fonts\/([^"')]+)/g)].map((m) => m[1]))];
  const keptModulesFiles = new Set([path.join(FIRE, 'fire/js/core.js'), path.join(FIRE, 'fire/js/icons.js'), ...[...closure.M.keys()].map((m) => path.join(FIRE, map.modules[m].file))]);
  const keptFiles = reachable([...keptModulesFiles]);
  const cat = (fs_) => Buffer.concat(fs_.map((f) => fs.readFileSync(f)));
  const allJs = reachable([path.join(FIRE, 'fire/fire.js')]);
  const fontBuf = (names) => Buffer.concat(names.map((n) => fs.readFileSync(path.join(FIRE, 'fire/fonts', n))));
  const imported = new Set(reachable([...keptModulesFiles]).map((f) => path.basename(f, '.js')));
  const viaElements = found.elements ? new Set(reachable([path.join(FIRE, 'fire/elements.js')]).map((f) => path.basename(f, '.js'))) : new Set();
  const order = Object.keys(map.modules);

  const report = {
    fire: map.fire, level, sources: opts.sources, theme: typeof opts.theme === 'string' ? opts.theme : record ? 'record' : null, include: opts.include || [],
    tweaks: closure.tweaks ? 'the Tweaks panel is used: every palette, type set and dial is kept' : null,
    kept: {
      components: Object.fromEntries([...closure.K].sort(([a], [b]) => a.localeCompare(b))),
      modules: Object.fromEntries(order.filter((m) => closure.M.has(m)).map((m) => [m, closure.M.get(m)])),
      stylesheets: css.sheets.filter((s) => s.kept).map((s) => s.file),
      palettes: css.live['data-palette'] ? [...css.live['data-palette']].sort() : 'all',
      typeSets: css.live['data-type'] ? [...css.live['data-type']].sort() : 'all',
      families: css.families.length ? css.families : 'all',
      fonts: css.fonts,
      // At `component` with a theme: the only values kept of each dial (none = only its default, which needs no rule).
      dials: Object.fromEntries(DIALS.filter((d) => css.live[d]).map((d) => [d, [...css.live[d]].sort()])),
    },
    dropped: {
      // Not used, and with no rule in tokens, base or layout (which are kept whole): the rules that name them are gone.
      components: Object.keys(map.components).filter((id) => !closure.K.has(id) && Object.keys(map.components[id].css).every((f) => f.startsWith('components/'))).sort(),
      modules: order.filter((m) => !closure.M.has(m) && !imported.has(m) && !viaElements.has(m)),
      bundledNotInitialised: order.filter((m) => !closure.M.has(m) && (imported.has(m) || viaElements.has(m))),
      stylesheets: css.sheets.filter((s) => !s.kept).map((s) => s.file),
      fonts: fullFonts.filter((f) => !css.fonts.includes(f)).sort(),
    },
    // How the product loads Fire: by the package name, by a path (/fire/fire.js, ../fire/js/content.js, a <script> tag), or both.
    // By path, the product must point that path at this output (replace the folder, or alias it) for the build to use it;
    // `unresolved` lists where Fire's namespace is used so that every module had to be kept.
    loadedBy: { by: found.loaded.package.size && found.loaded.path.size ? 'both' : found.loaded.path.size ? 'path' : found.loaded.package.size ? 'package' : 'none',
      specifiers: [...found.loaded.package, ...found.loaded.path].sort(), tags: found.loaded.tags, unresolved: found.loaded.unresolved },
    dynamic: found.dynamic,
    unknown: [...found.unknown, ...css.unknown.map((name) => ({ at: 'Fire\'s CSS', name }))],
    sizes: {
      css: { before: size(Buffer.from(fullCss)), after: size(Buffer.from(css.css)) },
      js: { before: size(cat(allJs)), after: size(cat(keptFiles)) },
      fonts: { before: size(fontBuf(fullFonts)), after: size(fontBuf(css.fonts)) },
    },
  };
  const files_ = {
    'fire.css': `/* GENERATED by fire slim (level ${level}); do not edit. What this product uses of Fire ${map.fire}: see slim.json. */\n${css.css}`,
    'fire.js': js + '\n',
    'slim.json': JSON.stringify(report, null, 2) + '\n',
  };
  if (opts.check) {
    const stale = Object.entries(files_).filter(([f, t]) => !fs.existsSync(path.join(out, f)) || fs.readFileSync(path.join(out, f), 'utf8') !== t).map(([f]) => f);
    const have = fs.existsSync(path.join(out, 'fonts')) ? fs.readdirSync(path.join(out, 'fonts')).sort() : [];
    if (have.join() !== css.fonts.join()) stale.push('fonts/');
    return { report, stale, out };
  }
  fs.mkdirSync(path.join(out, 'fonts'), { recursive: true });
  for (const [f, t] of Object.entries(files_)) if (!fs.existsSync(path.join(out, f)) || fs.readFileSync(path.join(out, f), 'utf8') !== t) fs.writeFileSync(path.join(out, f), t);
  for (const f of fs.readdirSync(path.join(out, 'fonts'))) if (!css.fonts.includes(f)) fs.rmSync(path.join(out, 'fonts', f));
  for (const f of css.fonts) if (!fs.existsSync(path.join(out, 'fonts', f))) fs.copyFileSync(path.join(FIRE, 'fire/fonts', f), path.join(out, 'fonts', f));
  return { report, stale: [], out };
}

/* ------------------------------------------------------------------ --verify: the production build */

export function verify(buildDir, report) {
  const map = JSON.parse(readFire('contract/slim-map.json'));
  const catalog = JSON.parse(readFire('contract/catalog.json'));
  const classOf = new Map(Object.entries(catalog.classes));
  const files = [];
  const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else files.push(p); } };
  walk(buildDir);
  const css = files.filter((f) => f.endsWith('.css')).map((f) => fs.readFileSync(f, 'utf8')).join('\n');
  const js = files.filter((f) => /\.m?js$/.test(f)).map((f) => fs.readFileSync(f, 'utf8')).join('\n');
  const problems = [];
  const dropped = new Set(report.dropped.components);
  const palettes = report.kept.palettes === 'all' ? null : new Set(report.kept.palettes);
  const seen = new Set();
  const walkCss = (nodes) => { for (const n of nodes) {
    if (n.children) { walkCss(n.children); continue; }
    if (n.type !== 'rule') continue;
    for (const s of selectorsOf(n.prelude)) {
      const need = needs(s);
      const bad = need.classes.find((c) => dropped.has(classOf.get(c))) || (palettes && need.attrs.find((a) => a.name === 'data-palette' && a.value && !palettes.has(a.value))?.value);
      if (bad && !seen.has(bad)) { seen.add(bad); problems.push(`the CSS still has a rule the report dropped: ${s.slice(0, 100)}`); }
    }
  } };
  const text = css;
  walkCss(splitCss(text));
  for (const m of report.dropped.modules) for (const sig of map.modules[m].signature) if (js.includes(sig)) problems.push(`the JS still holds the dropped module ${m} (it contains ${JSON.stringify(sig)})`);
  const fonts = files.filter((f) => /\.woff2?$/.test(f));
  const sizes = { css: size(Buffer.from(css)), js: size(Buffer.from(js)), fonts: { raw: fonts.reduce((n, f) => n + fs.statSync(f).size, 0), files: fonts.length } };
  return { problems, sizes };
}

function config(cwd) {
  for (let d = cwd; ; d = path.dirname(d)) {
    const p = path.join(d, 'package.json');
    if (fs.existsSync(p)) return { ...(JSON.parse(fs.readFileSync(p, 'utf8')).fire?.slim || {}), root: d };
    if (path.dirname(d) === d) return {};
  }
}

const kb = (n) => `${(n / 1024).toFixed(1)} kB`;
async function main(argv) {
  const opts = { sources: [] };
  let verifyDir = null, printReport = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i], next = () => argv[++i];
    if (a === '--out') opts.out = next();
    else if (a === '--theme') opts.theme = next();
    else if (a === '--include') opts.include = next().split(',').map((s) => s.trim()).filter(Boolean);
    else if (a === '--level') opts.level = next();
    else if (a === '--check') opts.check = true;
    else if (a === '--report') printReport = true;
    else if (a === '--verify') verifyDir = next();
    else if (a === '-h' || a === '--help') { console.log('usage: fire slim <sources…> --out <dir> [--theme theme.json] [--include a,b] [--level family|component] [--report] [--check] | --verify <build dir>'); return 0; }
    else if (a.startsWith('--')) { console.error(`fire slim: unknown option ${a}`); return 2; }
    else opts.sources.push(a);
  }
  const conf = config(process.cwd());
  const base = conf.root || process.cwd();
  if (!opts.sources.length) { opts.sources = conf.sources || []; opts.cwd = base; }
  opts.out ??= conf.out ? path.resolve(base, conf.out) : undefined;
  opts.theme ??= conf.theme ? path.resolve(base, conf.theme) : undefined;
  opts.include ??= conf.include;
  opts.level ??= conf.level;
  if (verifyDir) {
    const out = path.resolve(opts.out || '.fire-slim');
    const report = JSON.parse(fs.readFileSync(path.join(out, 'slim.json'), 'utf8'));
    const { problems, sizes } = verify(path.resolve(verifyDir), report);
    const s = report.sizes;
    console.log(`fire slim (${report.level}): sources CSS ${kb(s.css.before.raw)} -> ${kb(s.css.after.raw)} (gzip ${kb(s.css.before.gzip)} -> ${kb(s.css.after.gzip)}), JS ${kb(s.js.before.raw)} -> ${kb(s.js.after.raw)} (gzip ${kb(s.js.before.gzip)} -> ${kb(s.js.after.gzip)}), fonts ${kb(s.fonts.before.raw)} -> ${kb(s.fonts.after.raw)}`);
    console.log(`production build ${verifyDir}: CSS ${kb(sizes.css.raw)} (gzip ${kb(sizes.css.gzip)}), JS ${kb(sizes.js.raw)} (gzip ${kb(sizes.js.gzip)}), fonts ${kb(sizes.fonts.raw)} in ${sizes.fonts.files} files`);
    for (const p of problems.slice(0, 8)) console.error(`FAIL ${p}`);
    if (problems.length > 8) console.error(`FAIL … and ${problems.length - 8} more: the build does not use ${path.relative(process.cwd(), out)} (is the alias in place?)`);
    return problems.length ? 1 : 0;
  }
  try {
    const { report, stale, out } = await slim(opts);
    const rel = path.relative(process.cwd(), out) || '.';
    if (opts.check) {
      if (stale.length) { console.error(`fire slim: ${rel} is stale (${stale.join(', ')}): run fire slim`); return 1; }
      console.log(`fire slim: ${rel} is up to date`);
      return 0;
    }
    const s = report.sizes;
    console.log(`fire slim (${report.level}): ${Object.keys(report.kept.components).length} components, ${Object.keys(report.kept.modules).length} modules -> ${rel}; CSS ${kb(s.css.before.raw)} -> ${kb(s.css.after.raw)}, JS ${kb(s.js.before.raw)} -> ${kb(s.js.after.raw)}, fonts ${kb(s.fonts.before.raw)} -> ${kb(s.fonts.after.raw)}`);
    if (printReport) {
      console.log(`modules: ${Object.entries(report.kept.modules).map(([m, w]) => `${m} (${w})`).join('\n         ')}`);
      console.log(`dropped modules: ${report.dropped.modules.join(', ') || 'none'}; stylesheets: ${report.dropped.stylesheets.join(', ') || 'none'}`);
      if (report.tweaks) console.log(report.tweaks);
      const lb = report.loadedBy;
      if (lb.by !== 'package' && lb.by !== 'none') console.log(`Fire is loaded by path (${lb.specifiers.join(', ')}): point that path at ${rel} for the build to use it`);
      for (const t of lb.tags) console.log(`script ${t.src}  ${t.at}  (loads Fire by path; markup decides what is kept)`);
      for (const u of lb.unresolved) console.log(`every module kept: Fire's namespace from ${u.specifier} is used where no member can be read  ${u.at}`);
      for (const d of report.dynamic) console.log(`dynamic class ${d.expr}  ${d.at}  (keep what it builds with --include)`);
      for (const u of report.unknown) console.log(`unknown ${u.name}  ${u.at}`);
    }
    return 0;
  } catch (error) { console.error(error.message); return 1; }
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) process.exitCode = await main(process.argv.slice(2));
