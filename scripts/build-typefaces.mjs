#!/usr/bin/env node
/*
 * build-typefaces: writes the two files generated from the font catalogue and the named type sets.
 *
 *   node scripts/build-typefaces.mjs            write fire/js/fonts.js and fire/typefaces.css
 *   node scripts/build-typefaces.mjs --check    exit 1 when either is stale (what `node scripts/build.mjs --check` runs)
 *
 * Sources: contract/fonts.json (the catalogue: metrics, fallbacks, files, roles) and the twelve named sets in
 * fire/js/typefaces.js, each defined as a type set spec (the theme record's `type`). Nothing is written by hand in the
 * outputs. A set is added by adding its spec to TYPEFACES; a family by adding it to contract/fonts.json.
 *
 *   fire/js/fonts.js      the catalogue the browser-side theme module validates against: roles, voices, x-height,
 *                         weights and the fallback face's metrics for every family.
 *   fire/typefaces.css    the @font-face of every shipped family that tokens.css does not declare, the metric-matched
 *                         fallback faces, the heading-case and figures attributes, and one [data-type] block per set.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const catalogue = JSON.parse(read('contract/fonts.json'));

/* ---------- fire/js/fonts.js ---------- */

const families = catalogue.families.map((f) => {
  const o = {
    stack: f.stack, roles: f.roles, displayOnly: f.displayOnly, voices: f.voices, licence: f.licence, variable: f.variable,
    weightRange: f.weightRange, ...(f.weights ? { weights: f.weights } : {}), axes: Object.keys(f.axes),
    metrics: { xHeightRatio: f.metrics.xHeightRatio, capHeightRatio: f.metrics.capHeightRatio, xWidthAvgRatio: f.metrics.xWidthAvgRatio },
    fallback: { local: f.fallback.local, size: f.fallback.sizeAdjust, ascent: f.fallback.ascentOverride, descent: f.fallback.descentOverride, gap: f.fallback.lineGapOverride },
    ...(f.shipped ? { shipped: true } : {}), ...(f.core ? { core: true } : {}),
  };
  return `  ${JSON.stringify(f.name)}: ${JSON.stringify(o)},`;
});
const fontsJs = `/* GENERATED by scripts/build-typefaces.mjs from contract/fonts.json; do not edit by hand.
 * The font catalogue as the browser-side theme module needs it (checkTypeSpec in typefaces.js). The full entries (the
 * files, their checksums, the measured metrics, the npm source) are in contract/fonts.json.
 *   stack          which system stack ends the family's CSS stack: sans, serif or mono
 *   roles          display (headings), interface (the interface face), mono (code)
 *   displayOnly    never the interface face, whatever its x-height
 *   metrics        ratios of the em: x-height, cap height, average letter width
 *   fallback       the local() font and the metric overrides of its fallback face, in percent
 *   shipped        Fire's own fire/fonts/ has the files; core: tokens.css declares it (and gives it no fallback)
 */
export const INTERFACE_MIN_XHEIGHT = ${catalogue.interfaceMinXHeight};
export const FONT_STACKS = Object.freeze(${JSON.stringify(catalogue.stacks, null, 2).replace(/\n/g, '\n')});
export const VOICES = Object.freeze(${JSON.stringify(Object.keys(catalogue.voices))});
export const FONT_FAMILIES = Object.freeze({
${families.join('\n')}
});
`;
const fontsPath = path.join(ROOT, 'fire/js/fonts.js');
const stale = [];
const same = (file, text) => fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text;
if (CHECK) { if (!same(fontsPath, fontsJs)) stale.push('fire/js/fonts.js'); }
else fs.writeFileSync(fontsPath, fontsJs);

/* ---------- fire/typefaces.css ---------- */

const { TYPEFACES, DEFAULT_TYPEFACE, fontStack, fallbackFace, getFamily, checkTypeSpec } = await import(`${pathToFileURL(path.join(ROOT, 'fire/js/typefaces.js')).href}?${Date.now()}`);
const UNICODE = catalogue.subsets.latin.unicodeRange;
const byName = Object.fromEntries(catalogue.families.map((f) => [f.name, f]));

// A built-in set must be a valid spec (the rules it is excused are named on the set).
for (const t of TYPEFACES) {
  const { errors } = checkTypeSpec(t.spec, { path: `/${t.name}`, legacy: t.legacy ?? [] });
  if (errors.length) { console.error(`type set "${t.name}" breaks the pairing rules:\n  ${errors.join('\n  ')}`); process.exit(1); }
}

// Every family the sets use, in first-use order, the default's own (tokens.css declares them) left out.
const used = [];
for (const t of TYPEFACES) for (const k of ['display', 'sans', 'mono']) {
  const n = t.spec[k];
  if (n && !used.includes(n) && !getFamily(n)?.core) used.push(n);
}
const faceLines = used.flatMap((n) => byName[n].files.map((file) => {
  const fmt = file.variable ? 'woff2-variations' : 'woff2';
  return `@font-face { font-family: "${n}"; font-style: normal; font-display: swap; font-weight: ${file.weight}; src: url("./fonts/${file.file}") format("${fmt}"); unicode-range: ${UNICODE}; }`;
}));
const fallbackLines = used.map((n) => fallbackFace(n));

const LEVELS = [['display', 'display'], ['h1', 'h1'], ['h2', 'h2'], ['h3', 'h3']];
const block = (t) => {
  const s = t.spec;
  const lines = [`/* ${t.label}: ${t.note} */`, `[data-type="${t.name}"] {`];
  if (t.name === DEFAULT_TYPEFACE) {
    return [
      '/* Geist, the default. :root already has these values; this block restores them on a subtree that sits',
      '   inside another set (a Geist card on a page set to Poster). */',
      `[data-type="${t.name}"] {`,
      `  --fd-font-sans: ${fontStack(s.sans, 'sans')};`,
      `  --fd-font-mono: ${fontStack(s.mono, 'mono')};`,
      '  --fd-font-display: var(--fd-font-sans);',
      '  --fd-ls-display: -0.02em;',
      '  --fd-ls-h1: -0.02em;',
      '  --fd-ls-h2: -0.015em;',
      '  --fd-ls-h3: -0.005em;',
      '  --fd-weight-display: var(--fd-weight-medium);',
      '  --fd-text-display: 2.5rem; --fd-lh-display: 2.75rem;',
      '  --fd-text-h1: 2rem; --fd-lh-h1: 2.25rem;',
      '  --fd-text-h2: 1.5rem; --fd-lh-h2: 2rem;',
      '  --fd-text-h3: 1.25rem; --fd-lh-h3: 1.75rem;',
      '}',
    ].join('\n');
  }
  lines.push(`  --fd-font-display: ${fontStack(s.display, 'sans')};`, `  --fd-font-sans: ${fontStack(s.sans, 'sans')};`, `  --fd-font-mono: ${fontStack(s.mono, 'mono')};`);
  for (const [l] of LEVELS) lines.push(`  --fd-ls-${l}: ${s.displayTracking + 0}em;`);
  lines.push(`  --fd-weight-display: ${s.displayWeight};`);
  if (t.sizes) {
    lines.push(`  /* ${t.sizesNote} */`);
    for (const [l] of LEVELS) lines.push(`  --fd-text-${l}: ${t.sizes[l][0]}; --fd-lh-${l}: ${t.sizes[l][1]};`);
  }
  lines.push('}');
  return lines.join('\n');
};

const css = `/* ==========================================================================
   Fire — typefaces
   GENERATED by scripts/build-typefaces.mjs from the twelve sets in js/typefaces.js and the catalogue in
   contract/fonts.json; do not edit by hand (\`node scripts/build-typefaces.mjs\` rewrites it, --check verifies it).

   Eleven type sets beside the default (Geist). A set is one attribute:

     <html data-type="editorial">      on <html> or any subtree

   It sets the three voices (--fd-font-display for headings, --fd-font-sans for the interface,
   --fd-font-mono for code and eyebrows), and how headings are tracked and weighted in that face. A font file is only
   downloaded when a set that uses it is on the page. Each family's stack names a fallback face first (below): a
   local system font with size-adjust and ascent, descent and line-gap overrides measured against the web font, so
   the page does not move when the font arrives.

   A theme record can also write a type set spec of its own (fire/js/theme.js); two attributes carry its choices:

     data-heading-case="upper | sentence"     headings (.fd-display, .fd-h1 to .fd-h3, h1 to h3) in capitals, or as written
     data-figures="tabular | proportional"    figures in this subtree set in equal-width or natural-width digits

   All faces are open source (SIL Open Font License 1.1); licences are in fonts/licenses/.
   The files are the Latin subsets from Fontsource. To add a set: put its spec in js/typefaces.js and run the build;
   for a family the catalogue has, \`node scripts/fonts.mjs add "<family>"\` puts its files in the folder you choose.
   ========================================================================== */

${faceLines.join('\n')}

/* Fallback faces: Arial, Times New Roman or Courier New, resized to the web font's letter width and line box. */
${fallbackLines.join('\n')}

/* Headings in capitals, and figures of equal width, for a type set spec that asks. */
[data-heading-case="upper"] :is(.fd-display, .fd-h1, .fd-h2, .fd-h3, h1, h2, h3) { text-transform: uppercase; }
[data-heading-case="sentence"] :is(.fd-display, .fd-h1, .fd-h2, .fd-h3, h1, h2, h3) { text-transform: none; }
[data-figures="tabular"] { font-variant-numeric: tabular-nums; }
[data-figures="proportional"] { font-variant-numeric: proportional-nums; }

${TYPEFACES.map(block).join('\n')}
`;
const cssPath = path.join(ROOT, 'fire/typefaces.css');
if (CHECK) {
  if (!same(cssPath, css)) stale.push('fire/typefaces.css');
  if (stale.length) { console.error(`stale: ${stale.join(', ')}; run node scripts/build-typefaces.mjs`); process.exit(1); }
  console.log(`typefaces: fonts.js and typefaces.css are up to date (${catalogue.families.length} families, ${TYPEFACES.length} sets)`);
} else {
  fs.writeFileSync(cssPath, css);
  console.log(`typefaces: wrote fire/js/fonts.js (${catalogue.families.length} families) and fire/typefaces.css (${TYPEFACES.length} sets, ${used.length} families, ${faceLines.length} font files)`);
}
