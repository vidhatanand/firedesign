#!/usr/bin/env node
// contract/custom-elements.json → wrappers/react/elements.js and elements.d.ts: one React component per Fire custom
// element, made with @lit/react's createComponent, with prop types and event props read from the manifest.
// The hooks (hooks.js), the exporter's helpers (fire-export.js) and index.js beside them are hand-written.
//
// Usage: node scripts/build-wrappers.mjs [--check]
//   --check builds into a temporary folder and exits 1 when a committed output differs.
//
// Names: a tag `fd-chart` becomes `FireChart`; an event `fd:select` becomes the prop `onSelect` (`fd:` dropped, the
// rest in PascalCase after `on`). Every public instance field in the manifest is an element property: the component
// sets it on the element (createComponent decides property versus attribute with `name in elementClass.prototype`).
// The element classes cannot load on a server (they extend HTMLElement), so each component is given a stand-in
// class whose prototype names the manifest's fields; in the browser the module imports fire/elements.js, which
// registers the real elements (Lit applies properties set before the upgrade once the element is defined).
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUTS = ['wrappers/react/elements.js', 'wrappers/react/elements.d.ts'];
const HEAD = 'GENERATED by scripts/build-wrappers.mjs from contract/custom-elements.json: rebuild, never edit this file.';

/* ---------- read the manifest ---------- */
const manifest = JSON.parse(readFileSync(path.join(ROOT, 'contract/custom-elements.json'), 'utf8'));
const elements = manifest.modules
  .flatMap((mod) => mod.declarations ?? [])
  .filter((d) => d.customElement && d.tagName)
  .sort((a, b) => a.tagName.localeCompare(b.tagName))
  .map((d) => {
    const fields = (d.members ?? []).filter((m) => m.kind === 'field' && !m.static && (m.privacy ?? 'public') === 'public' && !m.name.startsWith('#'));
    const events = (d.events ?? []).filter((e) => e.name).map((e) => ({ ...e, prop: eventProp(e.name) }));
    return {
      tag: d.tagName,
      cls: d.name,
      component: componentName(d.tagName),
      summary: d.summary ?? '',
      fields: fields.map((f) => ({ name: f.name, type: typeText(f.type?.text), doc: f.description ?? '', attribute: f.attribute })),
      attributes: (d.attributes ?? []).map((a) => ({ name: a.name, field: a.fieldName, type: typeText(a.type?.text) })),
      events,
    };
  });
if (!elements.length) throw new Error('no custom elements in contract/custom-elements.json');

function componentName(tag) {
  return 'Fire' + tag.replace(/^fd-/, '').split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join('');
}
function eventProp(name) {
  return 'on' + name.replace(/^fd:/, '').split(/[-:]/).map((s) => s[0].toUpperCase() + s.slice(1)).join('');
}
function typeText(text) {
  const parts = String(text ?? 'unknown').split('|').map((s) => s.trim()).filter((s) => s && s !== 'undefined');
  return parts.length ? parts.join(' | ') : 'unknown';
}

/* ---------- where the named types come from ---------- */
const exported = (file) => new Set([...readFileSync(path.join(ROOT, file), 'utf8')
  .matchAll(/^export (?:declare )?(?:abstract )?(?:type|interface|class) ([A-Za-z0-9_]+)/gm)].map((m) => m[1]));
const fromElements = exported('fire/elements.d.ts');
const fromFire = exported('fire/fire.d.ts');
const typeNames = new Set();
for (const el of elements) {
  typeNames.add(el.cls);
  for (const f of el.fields) for (const id of f.type.match(/\b[A-Z][A-Za-z0-9_]*\b/g) ?? []) typeNames.add(id);
}
const importsElements = [...typeNames].filter((n) => fromElements.has(n)).sort();
const importsFire = [...typeNames].filter((n) => !fromElements.has(n) && fromFire.has(n)).sort();
const unknown = [...typeNames].filter((n) => !fromElements.has(n) && !fromFire.has(n));
if (unknown.length) throw new Error(`types not exported by fire/elements.d.ts or fire/fire.d.ts: ${unknown.join(', ')}`);
if (!importsFire.includes('FireEventMap')) importsFire.push('FireEventMap');
importsFire.sort();

/* ---------- elements.js ---------- */
const doc = (text, indent = '') => {
  const lines = String(text).trim().split('\n');
  return lines.length === 1 ? `${indent}/** ${lines[0]} */\n` : `${indent}/**\n${lines.map((l) => `${indent} * ${l}`.trimEnd()).join('\n')}\n${indent} */\n`;
};

function buildJs() {
  let out = `/* Fire's custom elements as React components (fire-design/react). ${HEAD}\n *\n`
    + ' * Each component renders its element and sets the element\'s properties (`data` on FireChart, `code` on FireCode)\n'
    + ' * after React commits; `fd:*` events are props (onSelect for fd:select, …). Use them in client components (in\n'
    + ' * Next.js: a file with "use client", or through this module, which is a client boundary). On the server they render\n'
    + ' * the bare tag; the element draws in the browser. */\n'
    + "'use client';\n"
    + "import * as React from 'react';\n"
    + "import { createComponent } from '@lit/react';\n\n"
    + '// In the browser, register the elements (a no-op when the page already did). Never on a server: they extend HTMLElement.\n'
    + "if (typeof window !== 'undefined' && typeof customElements !== 'undefined') import('../../fire/elements.js');\n\n"
    + '// Stand-ins for the element classes: createComponent reads only `name in elementClass.prototype` (which props are\n'
    + '// element properties) and the class name (the display name), so a prototype that names the fields is enough.\n'
    + 'const shape = (name, fields) => {\n'
    + '  const Element = { [name]: class {} }[name];\n'
    + '  for (const field of fields) Object.defineProperty(Element.prototype, field, { value: undefined, writable: true });\n'
    + '  return Element;\n'
    + '};\n';
  for (const el of elements) {
    out += `\n${doc(`<${el.tag}>: ${el.summary}`)}`;
    out += `export const ${el.component} = createComponent({\n`;
    out += '  react: React,\n';
    out += `  tagName: '${el.tag}',\n`;
    out += `  elementClass: shape('${el.cls}', [${el.fields.map((f) => `'${f.name}'`).join(', ')}]),\n`;
    out += `  events: {${el.events.length ? ' ' + el.events.map((e) => `${e.prop}: '${e.name}'`).join(', ') + ' ' : ''}},\n`;
    out += `  displayName: '${el.component}',\n`;
    out += '});\n';
  }
  return out;
}

/* ---------- elements.d.ts ---------- */
function buildDts() {
  let out = `/* Types of wrappers/react/elements.js. ${HEAD} */\n`
    + "import type * as React from 'react';\n"
    + `import type { ${importsElements.join(', ')} } from '../../fire/elements.js';\n`
    + `import type { ${importsFire.join(', ')} } from '../../fire/fire.js';\n\n`
    + '/** React\'s props for an element, without `style` (Fire\'s strict CSP rule: custom properties go in data-fd-vars) and\n'
    + ' *  without the React handlers whose names the element\'s own events take. */\n'
    + "export type FireHostProps<E extends HTMLElement, Events extends string = never> = Omit<React.HTMLAttributes<E>, 'style' | Events>;\n";
  for (const el of elements) {
    const evNames = el.events.map((e) => `'${e.prop}'`).join(' | ') || 'never';
    out += `\n/** Props of ${el.component} (<${el.tag}>). */\n`;
    out += `export interface ${el.component}Props extends FireHostProps<${el.cls}, ${evNames}> {\n`;
    for (const f of el.fields) out += doc(f.doc, '  ') + `  ${f.name}?: ${f.type};\n`;
    for (const e of el.events) out += doc(`\`${e.name}\`: ${e.description ?? ''}`, '  ') + `  ${e.prop}?: (event: FireEventMap['${e.name}']) => void;\n`;
    out += '}\n';
    out += doc(`<${el.tag}>: ${el.summary}`);
    out += `export declare const ${el.component}: React.ForwardRefExoticComponent<${el.component}Props & React.RefAttributes<${el.cls}>>;\n`;
  }
  out += '\n/* Writing the tags directly in TSX (<fd-chart …>): React 19 sets a prop as a property when the registered element has\n'
    + ' * one, and otherwise as an attribute; on the server, strings, numbers and `true` become attributes. Names are the\n'
    + ' * manifest\'s attributes; `class` works on custom elements. */\n';
  for (const el of elements) {
    out += `/** Attributes of <${el.tag}> in TSX. */\n`;
    out += `export interface ${el.cls}Attributes extends Omit<React.HTMLAttributes<${el.cls}>, 'style'>, React.RefAttributes<${el.cls}> {\n`;
    out += '  class?: string;\n';
    for (const a of el.attributes) out += `  ${/^[a-z][a-zA-Z0-9]*$/.test(a.name) ? a.name : `'${a.name}'`}?: ${a.type};\n`;
    out += '}\n';
  }
  out += "declare module 'react' {\n  namespace JSX {\n    interface IntrinsicElements {\n";
  for (const el of elements) out += `      '${el.tag}': ${el.cls}Attributes;\n`;
  out += '    }\n  }\n}\n';
  return out;
}

/* ---------- run ---------- */
const check = process.argv.includes('--check');
const outputs = { 'wrappers/react/elements.js': buildJs(), 'wrappers/react/elements.d.ts': buildDts() };

if (check) {
  const dir = mkdtempSync(path.join(tmpdir(), 'fire-wrappers-'));
  let stale = 0;
  try {
    for (const file of OUTPUTS) {
      const fresh = path.join(dir, file);
      mkdirSync(path.dirname(fresh), { recursive: true });
      writeFileSync(fresh, outputs[file]);
      const committed = path.join(ROOT, file);
      if (!existsSync(committed) || readFileSync(committed, 'utf8') !== readFileSync(fresh, 'utf8')) {
        console.error(`stale: ${file} (run node scripts/build-wrappers.mjs)`);
        stale += 1;
      }
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
  // index.js (hand-written) must re-export every generated component.
  const index = readFileSync(path.join(ROOT, 'wrappers/react/index.js'), 'utf8');
  for (const el of elements) {
    if (!new RegExp(`\\b${el.component}\\b`).test(index)) { console.error(`wrappers/react/index.js does not export ${el.component}`); stale += 1; }
  }
  if (stale) process.exit(1);
  console.log(`wrappers: ${OUTPUTS.length} outputs up to date (${elements.map((e) => e.component).join(', ')})`);
} else {
  for (const file of OUTPUTS) {
    mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true });
    writeFileSync(path.join(ROOT, file), outputs[file]);
  }
  console.log(`wrappers: wrote ${OUTPUTS.join(', ')} (${elements.map((e) => e.component).join(', ')})`);
}
