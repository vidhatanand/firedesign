// Writes the two files Fire needs that a build step must produce (spec H1, N2 for Vite):
//   public/fire/boot.js   Fire's boot script, copied so index.html can load it as a classic script
//   src/fire-theme.css    theme.json turned into a stylesheet (a strict CSP blocks a <style> written at run time)
// It also prints the <html> attributes the theme asks for; index.html carries them (see index.html).
//
//   node scripts/prepare.mjs [--theme path/to/record.json]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fire = path.dirname(createRequire(import.meta.url).resolve('fire-design/package.json'));
const flag = process.argv.indexOf('--theme');
const themeFile = path.resolve(root, flag > 0 ? process.argv[flag + 1] : 'theme.json');

const { themeToCss, expandTheme, validateTheme } = await import(pathToFileURL(path.join(fire, 'fire/js/theme.js')).href);
const record = JSON.parse(fs.readFileSync(themeFile, 'utf8'));
const { ok, errors } = validateTheme(record);
if (!ok) { console.error(`theme: ${themeFile} is not a valid theme record\n${errors.join('\n')}`); process.exit(1); }

fs.mkdirSync(path.join(root, 'public/fire'), { recursive: true });
for (const file of ['boot.js', 'favicon.svg']) fs.copyFileSync(path.join(fire, 'fire', file), path.join(root, 'public/fire', file));
fs.writeFileSync(path.join(root, 'src/fire-theme.css'), `/* Generated by scripts/prepare.mjs from ${path.basename(themeFile)}. Do not edit. */\n${themeToCss(record)}`);
// Written next to the stylesheet so index.html's attributes can be checked against the record: see README.
fs.writeFileSync(path.join(root, 'src/fire-theme.attributes.json'), JSON.stringify(expandTheme(record).attributes, null, 2) + '\n');
console.log(`theme: ${path.basename(themeFile)} -> src/fire-theme.css, public/fire/boot.js`);
